def main():
    global picam2
    picam2 = Picamera2()

    sensor_mode = None
    preferred = [
        ((1640, 1232), 8),
        ((1640, 1232), 10),
        ((3280, 2464), 8),
        ((3280, 2464), 10),
        ((1920, 1080), 8),
        ((1920, 1080), 10),
        ((640, 480), 8),
        ((640, 480), 10),
    ]
    for target_size, target_bit in preferred:
        for m in picam2.sensor_modes:
            if tuple(m.get("size", ())) == target_size and int(m.get("bit_depth", 0)) == target_bit:
                sensor_mode = m
                break
        if sensor_mode is not None:
            break
    if sensor_mode is None:
        sensor_mode = picam2.sensor_modes[0] if picam2.sensor_modes else None

    kwargs = {
        "main": {"size": (MAIN_W, MAIN_H), "format": "XRGB8888"},
        "lores": {"size": (LORES_W, LORES_H), "format": "YUV420"},
        "buffer_count": 4,
        "queue": False,
        "transform": Transform(hflip=CAMERA_ROTATE_180, vflip=CAMERA_ROTATE_180),
    }
    if sensor_mode is not None:
        kwargs["sensor"] = {
            "output_size": sensor_mode["size"],
            "bit_depth": sensor_mode["bit_depth"],
        }

    config = picam2.create_preview_configuration(**kwargs)
    picam2.configure(config)
    picam2.pre_callback = camera_callback
    picam2.start_preview(Preview.DRM, x=PREVIEW_X, y=PREVIEW_Y,
                         width=PREVIEW_W, height=PREVIEW_H)
    picam2.start()

    try:
        picam2.set_controls({"FrameDurationLimits": (16666, 33333)})
    except Exception:
        pass

    time.sleep(0.5)
    try:
        md = picam2.capture_metadata()
        exp = int(md.get("ExposureTime", 8000))
        exp = min(exp, 33000)
        ctrl = {
            "AeEnable": False,
            "AwbEnable": False,
            "ExposureTime": exp,
            "AnalogueGain": float(md.get("AnalogueGain", 1.0)),
        }
        colour = md.get("ColourGains", None)
        if colour is not None:
            ctrl["ColourGains"] = tuple(colour)
        picam2.set_controls(ctrl)
    except Exception:
        pass

    # Автозапуск (systemd / rc.local / автологин) останавливает программу
    # СИГНАЛОМ, а не Ctrl+C. По умолчанию Python на SIGTERM умирает мгновенно,
    # минуя finally, — тогда лог не дописывается и итоговый разбор не
    # создаётся. Превращаем сигнал в обычный выход, чтобы finally отработал.
    def _on_terminate(signum, _frame):
        raise SystemExit(128 + signum)

    for _sig in ("SIGTERM", "SIGHUP"):
        try:
            signal.signal(getattr(signal, _sig), _on_terminate)
        except Exception:
            # Не на всех платформах есть оба сигнала — не повод падать.
            pass

    flight_log.start()

    io_thread = threading.Thread(target=fc_io_loop, daemon=True)
    io_thread.start()

    try:
        while True:
            time.sleep(0.5)
    except (KeyboardInterrupt, SystemExit):
        # SystemExit сюда приходит из обработчика сигнала выше. Гасим его,
        # чтобы выйти штатно с кодом 0: для systemd это нормальная остановка.
        pass
    finally:
        # Первым делом дописываем лог: если ниже что-то зависнет на закрытии
        # железа, разбор полёта всё равно останется на диске.
        try:
            flight_log.stop()
        except Exception:
            pass
        io_thread_stop.set()
        try:
            if io_thread.is_alive():
                io_thread.join(timeout=1.0)
        except Exception:
            pass
        try:
            picam2.stop()
        except Exception:
            pass
        try:
            if fc is not None:
                fc.close()
        except Exception:
            pass


if __name__ == "__main__":
    main()
