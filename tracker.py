def clamp(v, lo, hi):
    return max(lo, min(hi, v))


def clamp_rect_center(cx, cy, w, h, max_w, max_h):
    w = max(2, int(round(w)))
    h = max(2, int(round(h)))
    x1 = int(round(cx - w / 2))
    y1 = int(round(cy - h / 2))
    x1 = clamp(x1, 0, max_w - w)
    y1 = clamp(y1, 0, max_h - h)
    return x1, y1, x1 + w, y1 + h


def crop_center(gray, cx, cy, w, h):
    x1, y1, x2, y2 = clamp_rect_center(cx, cy, w, h, gray.shape[1], gray.shape[0])
    return gray[y1:y2, x1:x2].copy(), (x1, y1, x2, y2)


def subpixel_peak(score_map, mx, my):
    """3-точечная параболическая интерполяция пика в score_map вокруг (mx, my).
    Возвращает (dx, dy) — субпиксельный сдвиг истинного пика относительно (mx, my),
    в диапазоне примерно [-0.5, 0.5]. Если пик на границе или в плоской зоне —
    возвращает (0, 0).
    Стоимость: 6 индексаций + 2 деления, в районе микросекунды.
    """
    h, w = score_map.shape[:2]
    dx = 0.0
    dy = 0.0
    if 0 < mx < w - 1:
        l = float(score_map[my, mx - 1])
        c = float(score_map[my, mx])
        r = float(score_map[my, mx + 1])
        denom = l - 2.0 * c + r
        if abs(denom) > 1e-6:
            dx = 0.5 * (l - r) / denom
            if dx < -0.5:
                dx = -0.5
            elif dx > 0.5:
                dx = 0.5
    if 0 < my < h - 1:
        t = float(score_map[my - 1, mx])
        c = float(score_map[my, mx])
        b = float(score_map[my + 1, mx])
        denom = t - 2.0 * c + b
        if abs(denom) > 1e-6:
            dy = 0.5 * (t - b) / denom
            if dy < -0.5:
                dy = -0.5
            elif dy > 0.5:
                dy = 0.5
    return dx, dy


def lores_box_to_main(cx, cy, w, h):
    sx = MAIN_W / LORES_W
    sy = MAIN_H / LORES_H
    x1 = int(round((cx - w / 2) * sx))
    y1 = int(round((cy - h / 2) * sy))
    x2 = int(round((cx + w / 2) * sx))
    y2 = int(round((cy + h / 2) * sy))
    x1 = clamp(x1, 0, MAIN_W - 1)
    y1 = clamp(y1, 0, MAIN_H - 1)
    x2 = clamp(x2, x1 + 1, MAIN_W)
    y2 = clamp(y2, y1 + 1, MAIN_H)
    return x1, y1, x2, y2


def refresh_flow_points(gray, cx, cy, w, h):
    patch, (x1, y1, x2, y2) = crop_center(gray, cx, cy, max(w * 2.2, 12), max(h * 2.2, 12))
    if patch.size == 0:
        return None
    pts = cv2.goodFeaturesToTrack(
        patch, maxCorners=25, qualityLevel=0.004, minDistance=2, blockSize=3
    )
    if pts is not None:
        pts = pts.astype(np.float32)
        pts[:, 0, 0] += x1
        pts[:, 0, 1] += y1
    return pts


def flow_predict(prev_g, cur_g, pts, cx, cy):
    if prev_g is None or pts is None or len(pts) < FLOW_MIN_POINTS:
        return False, cx, cy
    try:
        # Поток считаем по ОКНУ вокруг точек, а не по всему кадру.
        #
        # calcOpticalFlowPyrLK строит пирамиду по всей переданной картинке, и
        # это стоит пропорционально её ПЛОЩАДИ — независимо от того, что точек
        # всего два десятка. При переходе на 640x480 полный кадр обошёлся бы
        # вчетверо дороже каждый кадр, а Zero 2W упирается именно в процессор.
        #
        # Окно берём по границам точек плюс запас на их смещение. Точки
        # переводим в координаты окна, а результат возвращаем обратно —
        # снаружи функции ничего не меняется.
        pad = FLOW_WINDOW_PAD
        h_img, w_img = cur_g.shape[:2]
        use_window = FLOW_WINDOW_ENABLED
        xs, ys = pts[:, 0, 0], pts[:, 0, 1]
        wx1 = max(0, int(xs.min()) - pad)
        wy1 = max(0, int(ys.min()) - pad)
        wx2 = min(w_img, int(xs.max()) + pad + 1)
        wy2 = min(h_img, int(ys.max()) + pad + 1)
        # Слишком узкое окно пирамиде не годится — тогда работаем по кадру.
        if not use_window or (wx2 - wx1) < 32 or (wy2 - wy1) < 32:
            wx1, wy1, wx2, wy2 = 0, 0, w_img, h_img
        prev_win = prev_g[wy1:wy2, wx1:wx2]
        cur_win = cur_g[wy1:wy2, wx1:wx2]
        pts_win = pts.copy()
        pts_win[:, 0, 0] -= wx1
        pts_win[:, 0, 1] -= wy1

        nxt, st, err = cv2.calcOpticalFlowPyrLK(
            prev_win, cur_win, pts_win, None,
            winSize=(15, 15), maxLevel=2,
            criteria=(cv2.TERM_CRITERIA_EPS | cv2.TERM_CRITERIA_COUNT, 14, 0.03),
        )
        if nxt is not None:
            nxt = nxt.copy()
            nxt[:, 0, 0] += wx1
            nxt[:, 0, 1] += wy1
        if nxt is None or st is None:
            return False, cx, cy
        st = st.reshape(-1).astype(bool)
        old = pts[st].reshape(-1, 2)
        new = nxt[st].reshape(-1, 2)
        if err is not None:
            keep = err[st].reshape(-1) < FLOW_ERR_MAX
            old, new = old[keep], new[keep]
        if len(new) < FLOW_MIN_POINTS:
            return False, cx, cy
        dx = float(np.median(new[:, 0] - old[:, 0]))
        dy = float(np.median(new[:, 1] - old[:, 1]))
        if math.hypot(dx, dy) > FLOW_MAX_STEP:
            return False, cx, cy
        return True, cx + dx, cy + dy
    except Exception:
        return False, cx, cy


def estimate_size_at_position(gray, cx, cy, cur_w=None):
    """Оценка размера цели вокруг точки (cx, cy) по связной компоненте.

    Возвращает (lw, lh) либо (None, None), если ИЗМЕРИТЬ НЕ УДАЛОСЬ.

    Различие принципиальное. Раньше при неудаче возвращался размер по
    умолчанию (8 px) — то есть САМОЕ МАЛЕНЬКОЕ значение. А неудача происходит
    ровно тогда, когда цель КРУПНАЯ и не помещается в область поиска: связная
    компонента получалась шире R*1.6 и отвергалась. Адаптация это значение
    применяла, и коробка каждые 10 кадров возвращалась к минимуму. По логам
    борта она стояла на 16 px (в координатах кадра) в 76%% кадров.

    Следствие для крупного объекта: трекер вёл участок 8x8 его текстуры, а
    такой участок неотличим от участка фактурного фона — отсюда и «на крупном
    фактурном объекте фон перебивает».

    Теперь «не смог измерить» и «размер равен минимуму» — разные ответы, и
    вызывающая сторона сама решает, что делать.

    cur_w — текущий размер коробки. Область поиска растягивается под него,
    иначе крупная цель заведомо не помещается и измерить её невозможно.
    """
    R = ACQ_SIZE_SEARCH_RADIUS
    if cur_w:
        # Область должна вмещать цель с запасом, иначе компонента упрётся в
        # её границы и будет отвергнута как «слишком большая».
        R = int(max(R, min(SIZE_SEARCH_RADIUS_MAX, cur_w * 1.6)))
    cxi = int(round(cx))
    cyi = int(round(cy))
    x1 = max(0, cxi - R)
    y1 = max(0, cyi - R)
    x2 = min(gray.shape[1], cxi + R + 1)
    y2 = min(gray.shape[0], cyi + R + 1)
    roi = gray[y1:y2, x1:x2]
    if roi.size == 0:
        return None, None

    roi_f = roi.astype(np.float32)
    med = float(np.median(roi_f))
    std = float(np.std(roi_f))

    diff = np.abs(roi_f - med).astype(np.uint8)
    thr = int(max(3, min(30, std * 0.55 + 2)))
    _, mask = cv2.threshold(diff, thr, 255, cv2.THRESH_BINARY)
    kernel = np.ones((2, 2), np.uint8)
    mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, kernel)

    cx_local = cxi - x1
    cy_local = cyi - y1
    num_labels, labels, stats, _ = cv2.connectedComponentsWithStats(mask, connectivity=8)

    label = 0
    for r_search in (0, 1, 2):
        for dy in range(-r_search, r_search + 1):
            for dx in range(-r_search, r_search + 1):
                if abs(dx) != r_search and abs(dy) != r_search and r_search != 0:
                    continue
                ny = cy_local + dy
                nx = cx_local + dx
                if 0 <= ny < labels.shape[0] and 0 <= nx < labels.shape[1]:
                    lab = int(labels[ny, nx])
                    if lab > 0:
                        label = lab
                        break
            if label > 0:
                break
        if label > 0:
            break

    if label == 0 or label >= num_labels:
        return None, None

    x, y, w, h, area = stats[label]
    if area < 1:
        return None, None
    # Компонента упёрлась в границы области — значит цель как минимум такая,
    # но измерить её здесь нельзя. Отвечаем «не знаю», а НЕ минимальным
    # размером: подмена этих смыслов и ужимала коробку на крупных целях.
    if w > R * 1.6 or h > R * 1.6:
        return None, None

    lw = clamp(max(float(w) * LOCK_PAD, LOCK_MIN_W), LOCK_MIN_W, LOCK_MAX_W)
    lh = clamp(max(float(h) * LOCK_PAD, LOCK_MIN_H), LOCK_MIN_H, LOCK_MAX_H)
    return float(lw), float(lh)


def estimate_size_at_crosshair(gray):
    """Обёртка вокруг estimate_size_at_position для acquisition-фазы:
    оценивает размер ровно под прицелом.
    """
    return estimate_size_at_position(gray, CENTER_X_LORES, CENTER_Y_LORES)


def estimate_initial_target(gray):
    if ACQ_LOCK_AT_CROSSHAIR_EXACTLY:
        lw, lh = estimate_size_at_crosshair(gray)
        # При захвате «не измерили» означает «берём размер по умолчанию»:
        # цель ещё неизвестна, и начать с чего-то надо.
        if lw is None or lh is None:
            lw, lh = float(ACQ_DEFAULT_LOCK_W), float(ACQ_DEFAULT_LOCK_H)
        return float(CENTER_X_LORES), float(CENTER_Y_LORES), float(lw), float(lh), True
    return (float(CENTER_X_LORES), float(CENTER_Y_LORES),
            float(ACQ_DEFAULT_LOCK_W), float(ACQ_DEFAULT_LOCK_H), True)


def extract_chroma(yuv):
    """Достать плоскости U и V из буфера YUV420.

    Раскладка: сначала LORES_H строк яркости, затем по LORES_H/4 строк на U и
    на V — каждая строка шириной LORES_W содержит две строки по LORES_W/2.
    Цветность вдвое грубее яркости по обеим осям.
    """
    global chroma_fail_reason
    try:
        h, w = LORES_H, LORES_W
        q = h // 4
        # ВАЖНО: строки буфера могут быть ШИРЕ кадра (выравнивание, stride).
        # На это прямо намекает то, что яркость берётся как [:H, :W], а не
        # целиком. Раньше цветность бралась строками ЦЕЛИКОМ, и на выравненном
        # буфере reshape падал, исключение проглатывалось — цвет молча не
        # работал, различимость всегда выходила ровно 0.0.
        u = yuv[h:h + q, :w].reshape(h // 2, w // 2)
        v = yuv[h + q:h + 2 * q, :w].reshape(h // 2, w // 2)
        chroma_fail_reason = ""
        return u, v
    except Exception as exc:
        chroma_fail_reason = "разбор буфера: %s (форма %s)" % (
            exc, getattr(yuv, "shape", "?"))
        return None, None


def measure_color_separation(cx, cy, box_w, box_h):
    """Различает ли цвет цель и её окружение. Вызывается один раз при захвате.

    Сравнивается средняя цветность ЦЕЛИ со средней цветностью кольца вокруг
    неё. Если они близки — цвет информации не несёт (серое на сером), и его
    использование только добавило бы шума в решение. Тогда отсев по цвету
    остаётся выключенным до конца захвата, и поведение прежнее.

    Возвращает (подпись_цели, различимость).
    """
    global chroma_fail_reason
    if chroma_u is None or chroma_v is None:
        chroma_fail_reason = chroma_fail_reason or "цветность не прочитана"
        return None, 0.0
    ccx, ccy = int(cx) // 2, int(cy) // 2
    rw, rh = max(2, int(box_w) // 4), max(2, int(box_h) // 4)
    if rw < COLOR_MIN_TARGET_CHROMA_PX or rh < COLOR_MIN_TARGET_CHROMA_PX:
        chroma_fail_reason = ("цель мала: %dx%d px, радиус в цветности %d при "
                              "пороге %d" % (box_w, box_h, rw,
                                             COLOR_MIN_TARGET_CHROMA_PX))
        return None, 0.0
    H, W = chroma_u.shape
    def mean_box(arr, x0, y0, x1, y1):
        x0, y0 = max(0, x0), max(0, y0)
        x1, y1 = min(W, x1), min(H, y1)
        if x1 <= x0 or y1 <= y0:
            return None
        return float(arr[y0:y1, x0:x1].mean())
    tu = mean_box(chroma_u, ccx - rw, ccy - rh, ccx + rw, ccy + rh)
    tv = mean_box(chroma_v, ccx - rw, ccy - rh, ccx + rw, ccy + rh)
    # Кольцо вокруг цели — втрое шире по каждой оси.
    ou = mean_box(chroma_u, ccx - 3 * rw, ccy - 3 * rh, ccx + 3 * rw, ccy + 3 * rh)
    ov = mean_box(chroma_v, ccx - 3 * rw, ccy - 3 * rh, ccx + 3 * rw, ccy + 3 * rh)
    if None in (tu, tv, ou, ov):
        chroma_fail_reason = "область за границей кадра"
        return None, 0.0
    chroma_fail_reason = ""
    # Среднее по кольцу включает саму цель, поэтому отличие занижено — но нам
    # нужен именно консервативный критерий: лучше не включить цвет, чем
    # включить там, где он не различает.
    sep = abs(tu - ou) + abs(tv - ov)
    return (tu, tv), sep


def color_penalty_map(sx1, sy1, tw, th, shape):
    """Штраф за несовпадение цвета для каждой позиции кандидата.

    Для каждой позиции берётся средняя цветность области размером с цель и
    сравнивается с подписью, снятой при захвате. Считается на разрешении
    цветности (вдвое меньше) и растягивается до размера карты откликов.
    """
    if not color_active or target_uv is None or chroma_u is None:
        return None
    try:
        rh, rw = shape
        tu, tv = target_uv
        # Область цветности, покрывающая все центры кандидатов.
        cx0 = max(0, (sx1 + tw // 2) // 2 - 1)
        cy0 = max(0, (sy1 + th // 2) // 2 - 1)
        cx1 = min(chroma_u.shape[1], cx0 + rw // 2 + 3)
        cy1 = min(chroma_u.shape[0], cy0 + rh // 2 + 3)
        if cx1 - cx0 < 2 or cy1 - cy0 < 2:
            return None
        u = chroma_u[cy0:cy1, cx0:cx1].astype(np.float32)
        v = chroma_v[cy0:cy1, cx0:cx1].astype(np.float32)
        # Усредняем по площади цели: одиночный пиксель цветности слишком шумен.
        k = max(1, min(int(tw) // 4, min(u.shape) ))
        if k > 1:
            u = cv2.blur(u, (k, k))
            v = cv2.blur(v, (k, k))
        d = np.abs(u - tu) + np.abs(v - tv)
        d = np.clip(d / COLOR_REF_DIST, 0.0, 1.0)
        # Растягиваем до размера карты откликов (цветность вдвое грубее).
        return cv2.resize(d, (rw, rh), interpolation=cv2.INTER_LINEAR)
    except Exception:
        return None


def build_template(gray, cx, cy, box_w, box_h):
    global tmpl_w, tmpl_h, template_std
    tw = clamp(max(box_w * TEMPLATE_SCALE, TEMPLATE_MIN), TEMPLATE_MIN, TEMPLATE_MAX)
    th = clamp(max(box_h * TEMPLATE_SCALE, TEMPLATE_MIN), TEMPLATE_MIN, TEMPLATE_MAX)
    tmpl, rect = crop_center(gray, cx, cy, tw, th)
    template_std = float(np.std(tmpl)) if tmpl.size else 0.0
    tmpl_w = tmpl.shape[1]
    tmpl_h = tmpl.shape[0]
    return tmpl


def template_match_locked(gray, pred_cx, pred_cy, flow_motion=0.0):
    """Темплейт-матч с distance-penalty + субпиксельная интерполяция пика.

    flow_motion: модуль смещения flow-предсказания за кадр (px). Используется
    для адаптивного выбора SEARCH_MARGIN: на медленной цели окно меньше
    (быстрее матч, меньше шансов уцепиться за фон), на быстрой — больше.
    """
    global template_gray, tmpl_w, tmpl_h
    if template_gray is None or tmpl_w is None or tmpl_h is None:
        return False, pred_cx, pred_cy, 0.0

    # Адаптивный margin по скорости движения цели.
    if ADAPTIVE_SEARCH_MARGIN:
        vel_norm = flow_motion / SEARCH_MARGIN_VEL_REF
        if vel_norm > 1.0:
            vel_norm = 1.0
        margin = int(round(SEARCH_MARGIN_MIN + (SEARCH_MARGIN_MAX - SEARCH_MARGIN_MIN) * vel_norm))
    else:
        margin = SEARCH_MARGIN

    sw = int(tmpl_w + margin * 2)
    sh = int(tmpl_h + margin * 2)
    search, (sx1, sy1, sx2, sy2) = crop_center(gray, pred_cx, pred_cy, sw, sh)
    if search.shape[0] < tmpl_h or search.shape[1] < tmpl_w:
        return False, pred_cx, pred_cy, 0.0

    try:
        if template_std < 3.0:
            res = cv2.matchTemplate(search, template_gray, cv2.TM_SQDIFF_NORMED)
            score_map = 1.0 - res
        else:
            score_map = cv2.matchTemplate(search, template_gray, cv2.TM_CCOEFF_NORMED)
    except Exception:
        return False, pred_cx, pred_cy, 0.0

    if score_map.size == 0:
        return False, pred_cx, pred_cy, 0.0

    rh, rw = score_map.shape[:2]
    yy, xx = np.mgrid[0:rh, 0:rw]
    centers_x = sx1 + xx + tmpl_w / 2.0
    centers_y = sy1 + yy + tmpl_h / 2.0
    dist = np.sqrt((centers_x - pred_cx) ** 2 + (centers_y - pred_cy) ** 2)
    # Нормируем штраф по фактическому margin, не по константе.
    norm = max(margin, 1)
    penalized = score_map - DIST_PENALTY * (dist / norm) ** 2
    # Цветовой отсев. Добавляется к тому же штрафу, что и расстояние, поэтому
    # выбор пика учитывает цвет, но сама величина score остаётся чисто
    # яркостной — сравнимой с прежними логами.
    cmap = color_penalty_map(sx1, sy1, tmpl_w, tmpl_h, score_map.shape)
    if cmap is not None:
        penalized = penalized - COLOR_PENALTY * cmap

    _, max_val, _, max_loc = cv2.minMaxLoc(penalized.astype(np.float32))
    mx, my = max_loc
    raw_score = float(score_map[my, mx])

    # Насколько пик ОДИНОК. Если рядом есть почти такой же по силе кандидат,
    # матч неоднозначен: на фактурном фоне таких кандидатов много, и матчер
    # уверенно садится не на ту деталь, сохраняя приличный score. Обычная
    # уверенность этого не показывает — нужен именно контраст пика с фоном
    # карты откликов (это классический peak-to-sidelobe ratio).
    try:
        sm = score_map.astype(np.float32)
        mask = np.ones(sm.shape, dtype=bool)
        # ПОДОЗРЕНИЕ (проверять отдельным опытом): радиус исключения
        # привязан к размеру КАРТЫ ОТКЛИКОВ, а карта растёт вместе с окном
        # поиска. Считая для реальных величин:
        #     медленная цель, окно 14 -> карта ~29 px -> радиус 4
        #     быстрая цель,   окно 29 -> карта ~59 px -> радиус 8
        # Если собственный пик шире 4 px, то на медленных кадрах в «лучшего
        # конкурента» попадает ПЛЕЧО ТОГО ЖЕ ПИКА, а не другой кандидат.
        # Это объяснило бы, почему защита срабатывает на 45% медленных кадров
        # и лишь на 9% быстрых — и почему уменьшение фона в шаблоне (проба
        # TEMPLATE_SCALE=1.3) на эту долю никак не повлияло.
        # Правильнее привязывать радиус к размеру ШАБЛОНА, а не карты.
        r = max(2, int(min(sm.shape) * 0.15))
        y0, y1 = max(0, my - r), min(sm.shape[0], my + r + 1)
        x0, x1 = max(0, mx - r), min(sm.shape[1], mx + r + 1)
        mask[y0:y1, x0:x1] = False           # исключаем окрестность пика
        side = sm[mask]
        if side.size > 8:
            sd = float(side.std())
            psr = (raw_score - float(side.mean())) / sd if sd > 1e-6 else 0.0
            second = float(side.max())
        else:
            psr, second = 0.0, 0.0
        _match_dbg["psr"] = psr
        _match_dbg["second"] = second
        _match_dbg["margin"] = float(margin)
    except Exception:
        _match_dbg["psr"] = None
        _match_dbg["second"] = None
        _match_dbg["margin"] = float(margin)

    # Субпиксельное уточнение пика: убирает пиксельную квантовку матчера
    # (точность теперь ~0.1 px вместо ±0.5 px), особенно важно с маленьким
    # DEADBAND_X/Y — снимает «дребезг» крестика на покоящейся цели.
    sub_dx, sub_dy = subpixel_peak(score_map, mx, my)
    new_cx = sx1 + mx + sub_dx + tmpl_w / 2.0
    new_cy = sy1 + my + sub_dy + tmpl_h / 2.0

    if raw_score < MATCH_MIN_SCORE:
        return False, pred_cx, pred_cy, raw_score
    if math.hypot(new_cx - pred_cx, new_cy - pred_cy) > MAX_LOCK_STEP:
        return False, pred_cx, pred_cy, raw_score
    return True, float(new_cx), float(new_cy), raw_score


