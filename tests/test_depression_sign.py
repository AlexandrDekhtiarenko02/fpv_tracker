"""Знак угла снижения: нос вниз обязан давать ПОЛОЖИТЕЛЬНЫЙ угол.

Знак здесь установлен по замеру, а не по соглашению из документации:

  1. Картинка, которую получает трекер, НЕ перевёрнута — небо сверху
     (подтверждено оператором). Значит низ кадра это низ мира.
  2. Замерено по заходу 141912: цель в кадре смещается на -12.2 px на
     каждый +1° тангажа от FC, связь -0.92 на 207 кадрах.

При неперевёрнутой картинке цель уезжает ВВЕРХ, когда нос идёт ВНИЗ.
Значит рост тангажа от FC = нос вниз. Дальность считается до точки на
ЗЕМЛЕ, поэтому нос вниз обязан давать положительный угол снижения; при
обратном знаке дальность получалась бы до точки ПОЗАДИ аппарата.
"""
import io, os, re

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = io.open(os.path.join(_ROOT, "tracker.py"), encoding="utf-8").read()

m = re.search(r"^\s*depression = (.+)$", src, re.M)
assert m, "не нашёл вычисление угла снижения"
expr = m.group(1)
print("в коде:  depression =", expr)

MAIN_H = eval(re.search(r"^MAIN_W, MAIN_H = (.+?)(?:\s+#.*)?$", src, re.M).group(1))[1]
CAMERA_VFOV_DEG = eval(re.search(r"^CAMERA_VFOV_DEG = (.+?)(?:\s+#.*)?$", src, re.M).group(1))
CAMERA_TILT_DEG = eval(re.search(r"^CAMERA_TILT_DEG = (.+?)(?:\s+#.*)?$", src, re.M).group(1))
deg_per_px = CAMERA_VFOV_DEG / float(MAIN_H)

def depression(fc_pitch, off_deg, popravka=0.0):
    """Угол снижения по формуле ИЗ КОДА. popravka — поправка на занижение
    тангажа в полёте; в проверках знака она нулевая, чтобы не смешивать два
    разных вопроса."""
    return eval(expr, {"float": float, "fc_pitch": fc_pitch, "off_deg": off_deg,
                       "CAMERA_TILT_DEG": CAMERA_TILT_DEG,
                       "popravka": popravka})

print("\n=== 1. Нос вниз -> угол снижения положительный ===")
d = depression(20.0, 0.0)
print("    тангаж +20° (нос вниз), цель по центру -> угол %+.1f°" % d)
assert d > 0, "нос вниз даёт %.1f°: дальность считалась бы назад" % d

print("\n=== 2. Нос вверх -> угол отрицательный, дальности нет ===")
d = depression(-20.0, 0.0)
print("    тангаж -20° (нос вверх) -> угол %+.1f°" % d)
assert d < 0

print("\n=== 3. Цель НИЖЕ в кадре -> угол больше ===")
low = depression(10.0, +5.0)
high = depression(10.0, -5.0)
print("    цель ниже центра: %+.1f°, выше центра: %+.1f°" % (low, high))
assert low > high, "цель ниже в кадре обязана давать больший угол снижения"

print("\n=== 4. Тот самый заход: несли, наклонив к цели ===")
# Замерено: средний тангаж +14°, цель около центра. Прежний код объявлял это
# взглядом на 14° ВЫШЕ горизонта, что и объясняло 'дальность не считалась'.
d = depression(14.0, 0.0)
print("    тангаж +14° -> угол %+.1f° (прежний код давал %+.1f°)" % (d, -14.0))
assert d > 0

print("\n=== 5. Дальность выходит осмысленной ===")
import math
for alt_m, dep in ((30.0, 20.0), (30.0, 45.0), (50.0, 10.0)):
    r = alt_m / math.tan(math.radians(dep))
    print("    высота %.0f м, угол %.0f° -> дальность %.0f м" % (alt_m, dep, r))
    assert 0 < r < 1000

print("\n=== 6. Наклон камеры учтён: по горизонту угол около нуля ===")
# ЧИСЛО ФИЗИЧЕСКОЕ: камера на борту стоит под 10° вверх, это измерено на
# самом аппарате.
#
# Сюда же сходятся семь наземных замеров 4 сентября 2026 (дрон в руке,
# известные высота и дистанция): они дали 7.3-9.5°, медиана 8.5°.
#
# ОТДЕЛЬНО И НЕ СХОДИТСЯ: подгонка по сверке с GPS в полёте требует 0.5°.
# Разница около восьми градусов появляется только в воздухе, и причина
# неизвестна. Проверены и отвергнуты, каждая с цифрами: поправка поля зрения,
# множитель тангажа, масштаб высоты, влияние набегающего потока на барометр,
# задержка пакета углов, смещение координат цели.
#
# Стоит физическое значение: оно верно на земле и объяснимо, а полётное
# работало неизвестно почему. Цена решения замерена: на полётной выборке
# ошибка дальности с наклоном 9-10° выходит около 77% против 17% с 0.5°.
# То есть в воздухе дальности сейчас доверять нельзя, и это осознанный
# размен, пока причина расхождения не найдена.
d = depression(CAMERA_TILT_DEG, 0.0)
print("    тангаж = наклону камеры (%.1f°), цель по центру -> угол %+.2f°" % (CAMERA_TILT_DEG, d))
assert abs(d) < 0.05, (
    "при взгляде по горизонту угол обязан быть нулевым, а вышло %+.2f°: "
    "CAMERA_TILT_DEG не соответствует замеру" % d)
# Границы широкие намеренно: сторожим грубую ошибку (потерянный знак, ноль
# вместо величины, случай со столом), а не точное значение. Уточнять его
# должен новый замер по GPS, а не правка теста.
# Границы широкие: сторожим грубую ошибку (потерянный знак, ноль вместо
# величины), а не точное число. Оно спорно и меняется по мере замеров.
assert 0.0 < CAMERA_TILT_DEG < 20.0, (
    "наклон камеры %.2f° вне разумного: физически на борту 10°, наземные "
    "замеры дают 8.5°, полётная подгонка 0.5°" % CAMERA_TILT_DEG)
print("    наклон %.2f° (физически на борту 10°)" % CAMERA_TILT_DEG)

print("\n=== 7. Во что обошлась бы неучтённая четвёрка градусов ===")
import math as _m
for true_dep in (6.0, 10.0, 20.0):
    alt = 30.0
    r_true = alt / _m.tan(_m.radians(true_dep))
    r_bad = alt / _m.tan(_m.radians(true_dep + CAMERA_TILT_DEG))
    print("    истинный угол %.0f°: дальность %.0f м, без учёта наклона была бы %.0f м (%.0f%%)"
          % (true_dep, r_true, r_bad, 100 * r_bad / r_true))

print("\nOK: нос вниз даёт положительный угол, дальность считается вперёд")
