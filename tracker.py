def _pid_axis_step(error, prev_error, integral, ff_value,
                   p_gain, d_gain, i_gain, ff_gain,
                   integral_max, integral_decay,
                   sign, max_deflect, dbg_key=None, k=1.0):
    """Один шаг PID+FF по одной оси с условным anti-windup.

    Anti-windup: I-компонент НЕ накапливается, если P+D+FF+I-выход уже
    саттурирован в том же направлении, в котором новая I-добавка его
    толкала бы дальше. Это предотвращает overshoot, когда цель наконец-то
    оказывается в зоне досягаемости.

    ff_value: упреждающий сигнал (обычно скорость цели в пикселях/кадр).
    ff_gain: коэффициент пересчёта ff_value в PWM-вклад.
    Если ff_gain=0 — FF выключен, ведёт себя как чистый PID.

    Возвращает (offset_clamped, new_prev_error, new_integral).
    """
    err_f = float(error)
    d_err = err_f - prev_error

    # D и FF делятся на k, I умножается: при удвоенной частоте кадров разница
    # между кадрами вдвое меньше (её надо вернуть к номиналу), а накоплений за
    # ту же секунду вдвое больше (каждое должно быть вдвое меньше).
    pd_part = err_f * p_gain + (d_err / k) * d_gain
    ff_part = (float(ff_value) / k) * ff_gain

    # Сначала смотрим, где бы оказался выход с ТЕКУЩИМ интегратором.
    total_unsat = sign * (pd_part + ff_part + integral)
    sat_pos = total_unsat >= max_deflect
    sat_neg = total_unsat <= -max_deflect
    # Знак, в котором новая I-добавка толкнула бы выход.
    i_dir = sign * err_f
    push_further = (sat_pos and i_dir > 0) or (sat_neg and i_dir < 0)

    if err_f != 0.0 and not push_further:
        integral += err_f * i_gain * k
        if integral > integral_max:
            integral = integral_max
        elif integral < -integral_max:
            integral = -integral_max
    integral *= integral_decay ** k

    out = sign * (pd_part + ff_part + integral)
    saturated = False
    if out > max_deflect:
        out = max_deflect
        saturated = True
    elif out < -max_deflect:
        out = -max_deflect
        saturated = True

    if dbg_key is not None:
        # Раздельно P, D, I и FF: по сумме не понять, кто именно увёл ось —
        # а это первый вопрос, когда наведение промахивается.
        _pid_dbg[dbg_key] = (err_f * p_gain, d_err * d_gain, integral,
                             ff_part, out, saturated)

    return out, err_f, integral


def _estimate_closure(box_w, box_h, box_cy, now_mono, k):
    """Оценка сближения с целью. Возвращает словарь измерений.

    tau_s     — время до контакта, с. Из скорости роста коробки; реальный
                размер цели не нужен, он сокращается в отношении.
    range_m   — дальность по земле до цели, м. Из высоты и угла визирования.
    depression_deg — угол снижения линии визирования ниже горизонта.

    Величина None означает «оценить нельзя», а не «ноль»: не сближаемся,
    нет высоты, слишком малый угол. Смешивать эти случаи с нулём нельзя —
    ноль дальности означал бы «мы в цели».
    """
    global prev_box_size_px, box_growth_smoothed
    out = {"size_px": None, "growth": None, "tau_s": None,
           "range_m": None, "depression_deg": None}

    # --- время до контакта ---
    # Берём геометрическое среднее сторон: устойчивее к тому, что коробка
    # меняет пропорции при смене ракурса.
    size = math.sqrt(max(float(box_w), 1.0) * max(float(box_h), 1.0))
    out["size_px"] = size
    if prev_box_size_px is not None and prev_box_size_px > 0.0:
        # Относительный прирост за номинальный кадр.
        rel = ((size - prev_box_size_px) / prev_box_size_px) / k
        a = alpha_for_dt(TAU_GROWTH_ALPHA, k)
        box_growth_smoothed += a * (rel - box_growth_smoothed)
    prev_box_size_px = size
    out["growth"] = box_growth_smoothed
    if box_growth_smoothed > TAU_MIN_GROWTH:
        # Кадров до контакта -> секунд.
        out["tau_s"] = (1.0 / box_growth_smoothed) * NOMINAL_DT

    # --- дальность по наземной цели ---
    if not RANGE_ESTIMATE_ENABLED:
        return out
    with state_lock:
        alt_cm = app_state.get("alt_cm")
        alt_ts = app_state.get("alt_ts", 0.0)
        fc_pitch = app_state.get("fc_pitch_deg")
    if alt_cm is None or fc_pitch is None or (now_mono - alt_ts) > 1.0:
        return out

    # Угол цели относительно оси камеры: пиксели -> градусы.
    deg_per_px = CAMERA_VFOV_DEG / float(MAIN_H)
    off_deg = (float(box_cy) - CENTER_Y) * deg_per_px   # вниз по кадру = вниз
    # Нос вниз приходит от FC отрицательным, поэтому знак инвертируется:
    # чем сильнее опущен нос, тем больше угол снижения.
    depression = (-float(fc_pitch)) - CAMERA_TILT_DEG + off_deg
    out["depression_deg"] = depression

    alt_m = alt_cm / 100.0
    if depression >= RANGE_MIN_DEPRESSION_DEG and alt_m > 0.3:
        out["range_m"] = alt_m / math.tan(math.radians(depression))
    return out


def _pitch_angle_hold_pwm(target_deg, now_mono, k):
    """Команда тангажа, удерживающая ЗАДАННЫЙ УГОЛ наклона носа.

    Квад летит в ACRO: стик задаёт угловую СКОРОСТЬ. Чтобы получить угол,
    нужен внешний контур — он здесь и реализован, по реальному тангажу из
    MSP_ATTITUDE.

    Знак: нос вниз приходит от FC отрицательным (см. блок про MSP_ATTITUDE),
    поэтому цель тоже берётся отрицательной. К выходу применяется
    PITCH_PWM_TO_FC_ANGLE_SIGN, а НЕ PITCH_SIGN: последний описывает связь
    «пиксели -> PWM» и зависит от ориентации камеры, которая здесь ни при чём.

    Возвращает (pwm_offset, достигнут_ли_угол). Без свежего тангажа выдаёт 0:
    разомкнутый вариант — это ровно та ошибка, от которой уходим, и лучше не
    дать разгона совсем, чем крутить квад вслепую.
    """
    global prev_launch_pitch_deg
    with state_lock:
        fc_pitch = app_state.get("fc_pitch_deg")
        fc_ts = app_state.get("fc_pitch_ts", 0.0)

    if fc_pitch is None or (now_mono - fc_ts) > LAUNCH_ATT_TIMEOUT:
        prev_launch_pitch_deg = None
        return 0.0, False

    cur = float(fc_pitch)
    err = (-abs(target_deg)) - cur      # цель «нос вниз» в единицах FC

    d_term = 0.0
    if prev_launch_pitch_deg is not None:
        # Скорость изменения угла, приведённая к номинальному кадру.
        d_term = -((cur - prev_launch_pitch_deg) / k) * LAUNCH_ANGLE_D
    prev_launch_pitch_deg = cur

    out = PITCH_PWM_TO_FC_ANGLE_SIGN * (err * LAUNCH_ANGLE_P + d_term)
    if out > LAUNCH_MAX_PWM:
        out = LAUNCH_MAX_PWM
    elif out < -LAUNCH_MAX_PWM:
        out = -LAUNCH_MAX_PWM
    return out, abs(err) <= 2.0


def _compute_pitch_attitude_comp_px(now_mono, k=1.0):
    """Возвращает (compensation_px, обновлено?). Compensation добавляется
    к aim_y. Положительное значение = aim сдвигается ВНИЗ в кадре (бóльшая y),
    что соответствует ситуации «квад завален носом вниз → цель в кадре сверху,
    но это нормально для текущей траектории».

    Использует и обновляет глобал smoothed_pitch_deg.
    """
    global smoothed_pitch_deg
    if not PITCH_ATTITUDE_COMP_ENABLED:
        return 0.0

    with state_lock:
        fc_pitch = app_state.get("fc_pitch_deg")
        fc_pitch_ts = app_state.get("fc_pitch_ts", 0.0)

    if fc_pitch is None or (now_mono - fc_pitch_ts) > FC_PITCH_TIMEOUT:
        return 0.0

    smoothed_pitch_deg += alpha_for_dt(PITCH_COMP_ALPHA, k) * (
        float(fc_pitch) - smoothed_pitch_deg)
    comp_px = -smoothed_pitch_deg * PIXELS_PER_PITCH_DEG
    if comp_px > MAX_PITCH_COMP_PX:
        comp_px = MAX_PITCH_COMP_PX
    elif comp_px < -MAX_PITCH_COMP_PX:
        comp_px = -MAX_PITCH_COMP_PX
    return comp_px


def update_control_from_target():
    """Roll/Pitch/Yaw — P+D+I через _pid_axis_step с anti-windup.
       Прицельная точка по pitch учитывает текущий тангаж квада (MSP_ATTITUDE).
       Throttle:
         - OVERRIDE_THROTTLE=False (default) → target_throttle = live стик.
         - OVERRIDE_THROTTLE=True            → P+I+D по dy ОТ ЦЕНТРА КОРОБКИ
           (без AIM_OFFSET_Y, иначе I унесёт газ к нулю).

       Реальная отправка на FC решается в fc_io_loop по флагам OVERRIDE_*.
    """
    global global_yaw_cmd, global_pitch_cmd, global_roll_cmd, global_throttle_cmd, override_active
    global filtered_dx_yaw, prev_adx, prev_ady_ctrl
    global smooth_throttle_out, throttle_integral, prev_ady
    global roll_integral, pitch_integral, yaw_integral
    global smoothed_pitch_deg
    global prev_box_cx, prev_box_cy, target_vx_smoothed, target_vy_smoothed, stable_track_frames
    global launch_phase, launch_counter, prev_controllable_for_launch
    global overlay_text, overlay_color, _ctl_dbg, prev_control_mono
    global prev_launch_pitch_deg, prev_box_size_px, box_growth_smoothed

    with state_lock:
        box = target_box_main
        controllable = target_controllable
        live_thr = app_state.get("rc_throttle", 1500)
        live_thr_ts = app_state.get("rc_throttle_ts", 0.0)

    now_mono = time.monotonic()
    # Фактическая длительность кадра в единицах номинального (k=1 при 30 к/с).
    k = dt_ratio(None if prev_control_mono is None
                 else now_mono - prev_control_mono)
    prev_control_mono = now_mono
    # ОПОРНЫЙ ГАЗ — это стик пилота, и только он.
    #
    # Раньше при неактуальном RC сюда подставлялся dyn_throttle, то есть
    # СОБСТВЕННЫЙ выход прошлого кадра: target = base + поправка, затем
    # dyn_throttle = target, а на следующем кадре base = dyn_throttle. Газ
    # накручивал сам себя и упирался в 2000 — на борту это выглядело как
    # «при локе газ уходит в 100%», причём даже при стике на минимуме и при
    # нулевой поправке регулятора (thr_adj=0 в логах).
    #
    # Во время оверрайда стик законно «замирает»: Betaflight не отдаёт сырой
    # приёмник по подменяемым каналам. Замерший стик пилота — корректная
    # опора, а вот собственный выход опорой быть не может никогда.
    rc_valid = (885 <= int(live_thr) <= 2115) and live_thr_ts > 0.0
    base_thr = int(live_thr) if rc_valid else THROTTLE_MIN_PWM
    rc_fresh = rc_valid and ((now_mono - live_thr_ts) <= RC_FRESH_WINDOW)
    if base_thr < THROTTLE_MIN_PWM:
        base_thr = THROTTLE_MIN_PWM
    elif base_thr > THROTTLE_MAX_PWM:
        base_thr = THROTTLE_MAX_PWM

    if not controllable or box is None:
        # Сбрасываем ВСЕ накопители, иначе windup из прошлой сессии вылезет
        # на следующем TRACKED-кадре как «моторы сами раскрутились».
        filtered_dx_yaw = 0.0
        prev_adx = 0.0
        prev_ady_ctrl = 0.0
        prev_ady = 0.0
        smooth_throttle_out = None
        throttle_integral = 0.0
        roll_integral = 0.0
        pitch_integral = 0.0
        yaw_integral = 0.0
        smoothed_pitch_deg = 0.0
        prev_control_mono = None
        prev_launch_pitch_deg = None
        # Оценку сближения тоже сбрасываем: размер коробки после нового
        # захвата не связан с прежним, и прирост между ними — мусор.
        prev_box_size_px = None
        box_growth_smoothed = 0.0
        prev_box_cx = None
        prev_box_cy = None
        target_vx_smoothed = 0.0
        target_vy_smoothed = 0.0
        stable_track_frames = 0
        # Launch тоже сбрасывается — следующее controllable=True переоткроет манёвр.
        launch_phase = "NONE"
        launch_counter = 0
        prev_controllable_for_launch = False
        with state_lock:
            app_state["dyn_throttle"] = base_thr
            override_active = False
            global_roll_cmd = 1500.0
            global_pitch_cmd = 1500.0
            global_yaw_cmd = 1500.0
            global_throttle_cmd = base_thr
        # Кадр без управления — тоже данные: по ним видно, сколько времени
        # наведение простояло и в каком состоянии, вместо дыры в логе.
        _ctl_dbg = {"active": False, "base_thr": base_thr}
        return

    # --- Геометрия. РАЗДЕЛЬНЫЕ dy для pitch и для газа. ---
    box_cx = (box[0] + box[2]) / 2.0
    box_cy = (box[1] + box[3]) / 2.0

    # --- Launch state machine ---
    # Триггер: первый кадр, в котором мы controllable, после серии не-controllable
    # кадров (новый LOCK / возобновление после LOST). Прогон по фазам идёт
    # каждый кадр, не привязан к содержимому коробки или к ошибкам.
    trigger_launch = LAUNCH_ENABLED and not prev_controllable_for_launch
    prev_controllable_for_launch = True

    if trigger_launch:
        launch_phase = "RAMP_UP"
        launch_counter = 0

    launch_intensity = 0.0
    if launch_phase == "RAMP_UP":
        launch_intensity = launch_counter / float(max(LAUNCH_RAMP_UP_FRAMES, 1))
        if launch_intensity > 1.0:
            launch_intensity = 1.0
        # Шаг счётчика — k, а не 1: иначе при 60 к/с фаза launch проходила бы
        # вдвое быстрее по времени, чем задано константами.
        launch_counter += k
        if launch_counter >= LAUNCH_RAMP_UP_FRAMES:
            launch_phase = "HOLD"
            launch_counter = 0
    elif launch_phase == "HOLD":
        launch_intensity = 1.0
        launch_counter += k
        if launch_counter >= LAUNCH_HOLD_FRAMES:
            launch_phase = "RAMP_DOWN"
            launch_counter = 0
    elif launch_phase == "RAMP_DOWN":
        launch_intensity = 1.0 - launch_counter / float(max(LAUNCH_RAMP_DOWN_FRAMES, 1))
        if launch_intensity < 0.0:
            launch_intensity = 0.0
        launch_counter += k
        if launch_counter >= LAUNCH_RAMP_DOWN_FRAMES:
            launch_phase = "NONE"
            launch_counter = 0
            launch_intensity = 0.0
    # else: NONE — launch_intensity остаётся 0

    # Целевой угол: launch_intensity плавно поднимает его от 0 до
    # LAUNCH_TARGET_PITCH_DEG и так же плавно возвращает. Плавность теперь
    # относится к УГЛУ, а не к скорости вращения — поэтому раньше «плавный»
    # разгон и возврат и получались рывками.
    launch_pitch_pwm = 0.0
    cruise_pitch_pwm = 0.0
    launch_angle_reached = False
    if launch_intensity > 0.0:
        launch_pitch_pwm, launch_angle_reached = _pitch_angle_hold_pwm(
            LAUNCH_TARGET_PITCH_DEG * launch_intensity, now_mono, k)
    elif CRUISE_ENABLED and launch_phase == "NONE":
        cruise_pitch_pwm, _ = _pitch_angle_hold_pwm(
            CRUISE_TARGET_PITCH_DEG, now_mono, k)

    # --- Упреждение по скорости цели ---
    # Считаем межкадровую скорость, прогоняем через фильтр, отбрасываем глитчи.
    # Применяется только после LEAD_MIN_STABLE_FRAMES — даём фильтру стабилизироваться.
    lead_x = 0.0
    lead_y = 0.0
    if prev_box_cx is not None and prev_box_cy is not None:
        inst_vx = box_cx - prev_box_cx
        inst_vy = box_cy - prev_box_cy
        # Глитч-фильтр: re-lock / occlusion даёт скачок сильно больше реальной скорости цели.
        if abs(inst_vx) < LEAD_MAX_VEL_JUMP and abs(inst_vy) < LEAD_MAX_VEL_JUMP:
            # Мгновенная скорость измерена в пикселях ЗА КАДР; приводим к
            # номинальному кадру, иначе при 60 к/с она вдвое меньше при той же
            # физической скорости цели.
            a_vel = alpha_for_dt(LEAD_VEL_ALPHA, k)
            target_vx_smoothed += a_vel * (inst_vx / k - target_vx_smoothed)
            target_vy_smoothed += a_vel * (inst_vy / k - target_vy_smoothed)
            stable_track_frames += k
        else:
            # Подозрительный скачок — сбрасываем счётчик стабильности.
            stable_track_frames = 0
    prev_box_cx = box_cx
    prev_box_cy = box_cy

    if LEAD_AIM_ENABLED and stable_track_frames >= LEAD_MIN_STABLE_FRAMES and LEAD_FRAMES > 0:
        # target_v* уже приведены к номинальному кадру, поэтому горизонт
        # LEAD_FRAMES тоже трактуется в номинальных кадрах = фиксированное
        # время (LEAD_FRAMES/30 с), независимо от текущего FPS.
        lead_x = target_vx_smoothed * float(LEAD_FRAMES)
        lead_y = target_vy_smoothed * float(LEAD_FRAMES)
        # Жёсткий потолок чтобы шумы по скорости не унесли прицел через полкадра.
        if lead_x > LEAD_MAX_PX:
            lead_x = LEAD_MAX_PX
        elif lead_x < -LEAD_MAX_PX:
            lead_x = -LEAD_MAX_PX
        if lead_y > LEAD_MAX_PX:
            lead_y = LEAD_MAX_PX
        elif lead_y < -LEAD_MAX_PX:
            lead_y = -LEAD_MAX_PX

    # Динамическая компенсация наклона квада.
    pitch_comp_px = _compute_pitch_attitude_comp_px(now_mono, k)

    # Прицельная точка: текущая позиция + статический оффсет + компенсация тангажа + упреждение.
    dx_aim = (box_cx + AIM_OFFSET_X + lead_x) - CENTER_X
    dy_aim = (box_cy + AIM_OFFSET_Y + pitch_comp_px + lead_y) - CENTER_Y

    # Для газа — чистая позиция коробки, БЕЗ AIM_OFFSET, БЕЗ компенсации, БЕЗ упреждения.
    # Высоту мы корректируем по реальному положению цели, а не по предсказанному.
    dy_alt = box_cy - CENTER_Y

    adx = 0.0 if abs(dx_aim) < DEADBAND_X else (dx_aim - DEADBAND_X if dx_aim > 0 else dx_aim + DEADBAND_X)
    ady = 0.0 if abs(dy_aim) < DEADBAND_Y else (dy_aim - DEADBAND_Y if dy_aim > 0 else dy_aim + DEADBAND_Y)

    # --- Терминальный режим: близко к цели — другие гэйны ---
    # Когда коробка занимает заметную часть кадра, мы в финальных секундах.
    # Поднимаем P (нужны рефлексы), срезаем I (нет времени интегрировать),
    # чуть повышаем FF (резче следуем за движением цели).
    box_w_main = box[2] - box[0]
    box_h_main = box[3] - box[1]
    box_frac = (box_w_main * box_h_main) / float(MAIN_W * MAIN_H)
    in_terminal = TERMINAL_MODE_ENABLED and box_frac >= TERMINAL_BOX_FRAC_THRESHOLD

    # Оценка сближения. Пока ТОЛЬКО измеряется и пишется в лог — в закон
    # управления не входит (см. блок про оценку сближения выше).
    closure = _estimate_closure(box_w_main, box_h_main, box_cy, now_mono, k)

    if in_terminal:
        p_roll_eff = P_GAIN_ROLL * TERMINAL_P_MULTIPLIER
        p_pitch_eff = P_GAIN_PITCH * TERMINAL_P_MULTIPLIER
        i_roll_eff = I_GAIN_ROLL * TERMINAL_I_MULTIPLIER
        i_pitch_eff = I_GAIN_PITCH * TERMINAL_I_MULTIPLIER
        ff_roll_eff = FF_GAIN_ROLL * TERMINAL_FF_MULTIPLIER
        ff_pitch_eff = FF_GAIN_PITCH * TERMINAL_FF_MULTIPLIER
        ff_yaw_eff = FF_GAIN_YAW * TERMINAL_FF_MULTIPLIER
    else:
        p_roll_eff = P_GAIN_ROLL
        p_pitch_eff = P_GAIN_PITCH
        i_roll_eff = I_GAIN_ROLL
        i_pitch_eff = I_GAIN_PITCH
        ff_roll_eff = FF_GAIN_ROLL
        ff_pitch_eff = FF_GAIN_PITCH
        ff_yaw_eff = FF_GAIN_YAW

    # --- ROLL: P+D+I+FF через хелпер с anti-windup ---
    roll_offset, prev_adx, roll_integral = _pid_axis_step(
        adx, prev_adx, roll_integral,
        target_vx_smoothed,
        p_roll_eff, D_GAIN_ROLL, i_roll_eff, ff_roll_eff,
        ROLL_INTEGRAL_MAX, ROLL_INTEGRAL_DECAY,
        ROLL_SIGN, MAX_ROLL_DEFLECT, dbg_key="roll", k=k,
    )
    target_roll = max(1000, min(2000, 1500 + roll_offset))

    # --- PITCH: P+D+I+FF через хелпер с anti-windup ---
    pitch_offset, prev_ady_ctrl, pitch_integral = _pid_axis_step(
        ady, prev_ady_ctrl, pitch_integral,
        target_vy_smoothed,
        p_pitch_eff, D_GAIN_PITCH, i_pitch_eff, ff_pitch_eff,
        PITCH_INTEGRAL_MAX, PITCH_INTEGRAL_DECAY,
        PITCH_SIGN, MAX_PITCH_DEFLECT, dbg_key="pitch", k=k,
    )
    # Поверх PID — launch boost и cruise. Они могут вытолкнуть target_pitch
    # за MAX_PITCH_DEFLECT, но финальный clamp 1000-2000 остаётся.
    combined_pitch = pitch_offset + launch_pitch_pwm + cruise_pitch_pwm
    target_pitch = max(1000, min(2000, 1500 + combined_pitch))

    # --- YAW: фильтр + ослабление при больших adx + I + FF с anti-windup ---
    # Yaw не использует хелпер потому что error — это filtered_dx_yaw × yaw_weight,
    # а I-добавка тоже взвешивается. Логика та же, но с весом.
    filtered_dx_yaw += alpha_for_dt(YAW_FILTER_ALPHA, k) * (float(adx) - filtered_dx_yaw)
    abs_adx = abs(adx)
    if abs_adx < YAW_ROLL_CROSSOVER:
        yaw_weight = 1.0
    else:
        yaw_weight = max(0.3, 1.0 - (abs_adx - YAW_ROLL_CROSSOVER) / max(YAW_ROLL_BLEND_RANGE, 1.0))

    yaw_error_weighted = filtered_dx_yaw * yaw_weight
    yaw_pd = yaw_error_weighted * P_GAIN_YAW
    yaw_ff = target_vx_smoothed * ff_yaw_eff * yaw_weight
    yaw_total_unsat = YAW_SIGN * (yaw_pd + yaw_ff + yaw_integral)
    yaw_sat_pos = yaw_total_unsat >= MAX_YAW_DEFLECT
    yaw_sat_neg = yaw_total_unsat <= -MAX_YAW_DEFLECT
    yaw_i_dir = YAW_SIGN * yaw_error_weighted
    yaw_push_further = (yaw_sat_pos and yaw_i_dir > 0) or (yaw_sat_neg and yaw_i_dir < 0)
    if adx != 0 and not yaw_push_further:
        yaw_integral += yaw_error_weighted * I_GAIN_YAW * k
        if yaw_integral > YAW_INTEGRAL_MAX:
            yaw_integral = YAW_INTEGRAL_MAX
        elif yaw_integral < -YAW_INTEGRAL_MAX:
            yaw_integral = -YAW_INTEGRAL_MAX
    yaw_integral *= YAW_INTEGRAL_DECAY ** k

    yaw_offset = YAW_SIGN * (yaw_pd + yaw_ff + yaw_integral)
    if yaw_offset > MAX_YAW_DEFLECT:
        yaw_offset = MAX_YAW_DEFLECT
    elif yaw_offset < -MAX_YAW_DEFLECT:
        yaw_offset = -MAX_YAW_DEFLECT
    target_yaw = max(1000, min(2000, 1500 + yaw_offset))

    # --- THROTTLE ---
    thr_adjust = 0.0
    if not OVERRIDE_THROTTLE:
        target_throttle = base_thr
        smooth_throttle_out = float(base_thr)
        throttle_integral = 0.0
        prev_ady = float(dy_alt)
    else:
        # Динамика по dy_alt (БЕЗ AIM_OFFSET).
        thr_adjust = 0.0
        if abs(dy_alt) > THROTTLE_DEADBAND:
            active_dy = float(dy_alt - THROTTLE_DEADBAND if dy_alt > 0 else dy_alt + THROTTLE_DEADBAND)
            thr_adjust += -active_dy * DY_THROTTLE_GAIN
            throttle_integral += -active_dy * DY_INTEGRAL_RATE * k
            throttle_integral = max(-DY_INTEGRAL_MAX, min(DY_INTEGRAL_MAX, throttle_integral))
        else:
            throttle_integral *= 0.85 ** k

        throttle_integral *= DY_INTEGRAL_DECAY ** k
        thr_adjust += throttle_integral

        d_dy = float(dy_alt) - prev_ady
        prev_ady = float(dy_alt)
        thr_adjust += (d_dy / k) * DY_THROTTLE_D_GAIN

        max_adj = max(30.0, base_thr * THROTTLE_PERCENT / 100.0)
        thr_adjust = max(-max_adj, min(max_adj, thr_adjust))

        raw_throttle = base_thr + thr_adjust
        raw_throttle = max(THROTTLE_MIN_PWM, min(THROTTLE_MAX_PWM, raw_throttle))

        if smooth_throttle_out is None:
            smooth_throttle_out = float(raw_throttle)
        else:
            smooth_throttle_out += alpha_for_dt(THROTTLE_OUT_ALPHA, k) * (
                raw_throttle - smooth_throttle_out)
        target_throttle = int(round(smooth_throttle_out))
        target_throttle = max(THROTTLE_MIN_PWM, min(THROTTLE_MAX_PWM, target_throttle))

    # Launch throttle boost — применяется ТОЛЬКО при OVERRIDE_THROTTLE=True,
    # чтобы не наступать на ручное управление пилота.
    if OVERRIDE_THROTTLE and launch_intensity > 0.0 and LAUNCH_THR_BOOST_PCT > 0.0:
        # Буст считается от опорного стика пилота. Пока base_thr брался из
        # собственного выхода, буст начислялся на уже забустованное значение —
        # это давало не прибавку в 10%, а экспоненциальный разгон до упора.
        boost = base_thr * (LAUNCH_THR_BOOST_PCT / 100.0) * launch_intensity
        boosted = target_throttle + boost
        if boosted > THROTTLE_MAX_PWM:
            boosted = THROTTLE_MAX_PWM
        elif boosted < THROTTLE_MIN_PWM:
            boosted = THROTTLE_MIN_PWM
        target_throttle = int(round(boosted))

    # Индикация фазы launch в overlay (имеет приоритет над TRACKED/LOCK).
    if launch_phase in ("RAMP_UP", "HOLD", "RAMP_DOWN"):
        with state_lock:
            overlay_text = "LAUNCH"
            overlay_color = COLOR_CYAN

    with state_lock:
        app_state["dyn_throttle"] = target_throttle
        override_active = True
        global_roll_cmd = target_roll
        global_pitch_cmd = target_pitch
        global_yaw_cmd = target_yaw
        global_throttle_cmd = target_throttle

    # Снимок для лога. Собирается здесь, потому что это единственное место, где
    # видны все промежуточные величины сразу; снаружи их уже не восстановить.
    r_p, r_d, r_i, r_ff, r_off, r_sat = _pid_dbg.get("roll", (0.0,) * 5 + (False,))
    p_p, p_d, p_i, p_ff, p_off, p_sat = _pid_dbg.get("pitch", (0.0,) * 5 + (False,))
    _ctl_dbg = {
        "active": True,
        "box_cx": box_cx, "box_cy": box_cy,
        "box_w": box_w_main, "box_h": box_h_main, "box_frac": box_frac,
        "dx_raw": box_cx - CENTER_X, "dy_raw": box_cy - CENTER_Y,
        "comp": pitch_comp_px, "lead_x": lead_x, "lead_y": lead_y,
        "dx_aim": dx_aim, "dy_aim": dy_aim, "adx": adx, "ady": ady,
        "dy_alt": dy_alt,
        "tgt_vx": target_vx_smoothed, "tgt_vy": target_vy_smoothed,
        "stable": stable_track_frames, "terminal": in_terminal,
        "roll_p": r_p, "roll_d": r_d, "roll_i": r_i, "roll_ff": r_ff,
        "roll_off": r_off, "roll_sat": r_sat,
        "pitch_p": p_p, "pitch_d": p_d, "pitch_i": p_i, "pitch_ff": p_ff,
        "pitch_off": p_off, "pitch_sat": p_sat,
        "launch_pwm": launch_pitch_pwm, "cruise_pwm": cruise_pitch_pwm,
        "pitch_comb": combined_pitch,
        "yaw_filt": filtered_dx_yaw, "yaw_weight": yaw_weight,
        "yaw_pd": yaw_pd, "yaw_ff": yaw_ff, "yaw_i": yaw_integral,
        "yaw_off": yaw_offset,
        "yaw_sat": abs(yaw_offset) >= MAX_YAW_DEFLECT,
        "base_thr": base_thr, "thr_adjust": thr_adjust,
        "thr_i": throttle_integral, "rc_fresh": rc_fresh,
        "launch_phase": launch_phase, "launch_int": launch_intensity,
        # Целевой угол разгона и признак его достижения: по ним видно,
        # вышел ли квад на угол или контур всё ещё догоняет.
        "launch_target_deg": LAUNCH_TARGET_PITCH_DEG * launch_intensity,
        "launch_reached": launch_angle_reached,
        "k": k,
        "size_px": closure["size_px"], "growth": closure["growth"],
        "tau_s": closure["tau_s"], "range_m": closure["range_m"],
        "depression_deg": closure["depression_deg"],
        # Вертикальная ошибка газа, ОЧИЩЕННАЯ от собственного наклона.
        # Сейчас регулятор газа работает по сырому dy_alt, и наклон носа он
        # читает как «цель ушла вверх» — то есть разгон сам себе подкручивает
        # газ. Пишем очищенный вариант рядом, чтобы на живых заходах увидеть,
        # насколько это расходится, прежде чем менять закон управления.
        "dy_alt_decoupled": dy_alt + pitch_comp_px,
    }

