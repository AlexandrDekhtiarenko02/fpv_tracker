"""Частота кадров закрепляется жёстко, а не задаётся вилкой.

Замерено в полёте 4 сентября 2026: обработка кадра занимает 25-31 мс при
90-м процентиле 40.5, а предел длительности кадра стоял 33.3 мс. Камера в
такие моменты роняет кадр, и частота скачет — 20.9 к/с в одном заходе против
27.2 в соседнем.

Для сбора данных это хуже, чем просто низкая частота: по интервалу между
кадрами считаются скорость роста цели и время до контакта, и гуляющий вдвое
интервал портит обе величины.

Проверка идёт по исходному тексту: важно, что в программе НЕТ вилки, и что
частота закрепляется ПОВТОРНО после заморозки выдержки — в части версий
libcamera установка ExposureTime сбрасывает предел длительности кадра.
"""
import io
import os
import re

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = io.open(os.path.join(_ROOT, "tracker.py"), encoding="utf-8").read()

print("=== 1. Частота задана одним числом ===")
m = re.search(r"^CAM_FPS\s*=\s*([\d.]+)", src, re.M)
assert m, "нет настройки CAM_FPS"
fps = float(m.group(1))
print("    CAM_FPS =", fps)
assert 10.0 <= fps <= 60.0, "частота вне разумного"

print("\n=== 2. Вилки больше нет ===")
vilki = re.findall(r"FrameDurationLimits\"?\s*[:=]\s*\(([^)]*)\)", src)
print("    найдено установок:", len(vilki))
assert vilki, "частота кадров не задаётся вовсе"
for v in vilki:
    a, b = [x.strip() for x in v.split(",")]
    print("    (%s, %s)" % (a, b))
    assert a == b, (
        "предел кадра задан вилкой (%s, %s) — камера будет ронять кадры под "
        "нагрузкой, и частота поедет" % (a, b))

print("\n=== 3. Закрепляется ПОВТОРНО после заморозки выдержки ===")
# Иначе в части версий libcamera частота уедет обратно к «как получится»,
# причём молча и только на борту.
i = src.index("\"ExposureTime\": exp")
hvost = src[i:i + 1400]
assert "FrameDurationLimits" in hvost, (
    "после заморозки выдержки частота не закрепляется заново — уедет молча")
print("    закрепляется")

print("\n=== 4. Бюджет кадра больше замеренной обработки ===")
budget = 1000.0 / fps
# Замер на борту 4 сентября: 21.9 мс медиана, 40.5 мс 90-й процентиль.
print("    бюджет %.1f мс против замеренных 21.9 (медиана) и 40.5 (90%%)"
      % budget)
assert budget > 21.9, "бюджет меньше медианы обработки — кадры будут теряться"

print("\nOK: интервал между кадрами ровный, а не «как получится»")
