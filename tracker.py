def process_locked_tracker(gray):
    global track_state, target_visible, target_controllable, overlay_text, overlay_color, target_box_main
    global lock_cx, lock_cy, lock_w, lock_h, template_gray, prev_gray, prev_pts
    global template_base, target_uv, color_active, color_separation
    global lost_frames, frame_index, last_match_score, last_flow_ok
    global fps_t0, fps_frames, fps_current
    global prev_aux_on, acq_wait_left, lock_sequence
    global auto_reacq_attempts

    frame_index += 1

    with state_lock:
        aux_on = aux4_state
        live_thr = app_state.get("rc_throttle", 1500)

    rising_aux = aux_on and not prev_aux_on
    falling_aux = (not aux_on) and prev_aux_on
    prev_aux_on = aux_on

    if not aux_on:
        if falling_aux or track_state != TRACK_STATE_IDLE:
            reset_tracking(to_acq=False)
        auto_reacq_attempts = 0
        with state_lock:
            global global_roll_cmd, global_pitch_cmd, global_yaw_cmd, global_throttle_cmd, override_active
            override_active = False
            global_roll_cmd = 1500.0
            global_pitch_cmd = 1500.0
            global_yaw_cmd = 1500.0
            global_throttle_cmd = live_thr
        return

    if rising_aux:
        reset_tracking(to_acq=True)
        acq_wait_left = ACQ_SETTLE_FRAMES
        lock_sequence += 1
        auto_reacq_attempts = 0

    if track_state == TRACK_STATE_IDLE:
        reset_tracking(to_acq=True)
        acq_wait_left = ACQ_SETTLE_FRAMES

    if acq_wait_left > 0:
        acq_wait_left -= 1
        with state_lock:
            track_state = TRACK_STATE_ACQ
            target_visible = False
            target_controllable = False
            target_box_main = None
            overlay_text = "ACQ"
            overlay_color = COLOR_WHITE
        update_control_from_target()
        return

    if track_state == TRACK_STATE_LOST and REQUIRE_AUX_TOGGLE_AFTER_LOST:
        # Авто-восстановление: в течение AUTO_REACQ_FRAMES после LOST
        # пробуем найти цель в расширенном окне с высоким порогом матча.
        # Если получилось — без снятия AUX возвращаемся в TRACKED.
        # Иначе остаёмся в LOST/TOGGLE и ждём явного действия оператора.
        if (AUTO_REACQ_ENABLED and template_gray is not None
                and lock_cx is not None and auto_reacq_attempts < AUTO_REACQ_FRAMES):
            auto_reacq_attempts += 1
            # Расширенный матч в окне AUTO_REACQ_SEARCH_MARGIN px вокруг последнего lock.
            # Используем flow_motion=AUTO_REACQ_SEARCH_MARGIN, чтобы template_match_locked
            # автоматически развернул search-окно до максимума.
            match_ok_r, mcx, mcy, score_r = template_match_locked(
                gray, lock_cx, lock_cy, flow_motion=float(AUTO_REACQ_SEARCH_MARGIN)
            )
            if match_ok_r and score_r >= AUTO_REACQ_MIN_SCORE:
                # Нашли с уверенностью — возвращаемся в TRACKED, переинициализируем flow.
                lock_cx = float(mcx)
                lock_cy = float(mcy)
                prev_gray = gray.copy()
                prev_pts = refresh_flow_points(gray, lock_cx, lock_cy, lock_w, lock_h)
                lost_frames = 0
                last_match_score = score_r
                last_flow_ok = False
                auto_reacq_attempts = 0
                box = lores_box_to_main(lock_cx, lock_cy, lock_w, lock_h)
                with state_lock:
                    track_state = TRACK_STATE_TRACKED
                    target_visible = True
                    target_controllable = True
                    target_box_main = box
                    overlay_text = "REACQ"
                    overlay_color = COLOR_RED
                update_control_from_target()
                return
            # Не нашли в этом кадре — продолжаем висеть в LOST, повторим в следующем.
            with state_lock:
                target_visible = False
                target_controllable = False
                target_box_main = None
                overlay_text = "REACQ?"
                overlay_color = COLOR_YELLOW
            update_control_from_target()
            return

        # Окно auto-reacq исчерпано или выключено — обычное поведение LOST/TOGGLE.
        with state_lock:
            target_visible = False
            target_controllable = False
            target_box_main = None
            overlay_text = "LOST/TOGGLE"
            overlay_color = COLOR_WHITE
        update_control_from_target()
        return

    if track_state == TRACK_STATE_ACQ or (track_state == TRACK_STATE_LOST and not REQUIRE_AUX_TOGGLE_AFTER_LOST):
        acq_cx, acq_cy, lw, lh, ok = estimate_initial_target(gray)
        if ok:
            lock_cx = float(acq_cx)
            lock_cy = float(acq_cy)
            lock_w = float(lw)
            lock_h = float(lh)
            template_gray = build_template(gray, lock_cx, lock_cy, lock_w, lock_h)
            template_base = template_gray.copy()
            # Один раз на захват решаем, помогает ли цвет. Если цель и её
            # окружение одного цвета — цвет не включаем, поведение прежнее.
            if COLOR_GUARD_ENABLED:
                target_uv, color_separation = measure_color_separation(
                    lock_cx, lock_cy, lock_w, lock_h)
                color_active = (target_uv is not None
                                and color_separation >= COLOR_MIN_SEPARATION)
                if color_active:
                    flight_log.event(
                        "ЦВЕТ включён: различимость %.1f (порог %.1f)"
                        % (color_separation, COLOR_MIN_SEPARATION))
                else:
                    flight_log.event(
                        "ЦВЕТ не используется: различимость %.1f (порог %.1f)%s"
                        % (color_separation, COLOR_MIN_SEPARATION,
                           (" | причина: " + chroma_fail_reason)
                           if chroma_fail_reason else ""))
            else:
                color_active = False
            prev_gray = gray.copy()
            prev_pts = refresh_flow_points(gray, lock_cx, lock_cy, lock_w, lock_h)
            lost_frames = 0
            last_match_score = 1.0
            last_flow_ok = False
            box = lores_box_to_main(lock_cx, lock_cy, lock_w, lock_h)
            with state_lock:
                track_state = TRACK_STATE_TRACKED
                target_visible = True
                target_controllable = True
                target_box_main = box
                overlay_text = "LOCK"
                overlay_color = COLOR_RED
            update_control_from_target()
        else:
            with state_lock:
                track_state = TRACK_STATE_ACQ
                target_visible = False
                target_controllable = False
                target_box_main = None
                overlay_text = "ACQ"
                overlay_color = COLOR_WHITE
            update_control_from_target()
        return

    if lock_cx is None or lock_w is None or template_gray is None:
        reset_tracking(to_acq=True)
        return

    flow_ok, pred_cx, pred_cy = flow_predict(prev_gray, gray, prev_pts, lock_cx, lock_cy)
    # Модуль flow-предсказанного смещения цели за кадр — используется
    # template_match_locked для адаптивного выбора search-окна.
    flow_motion = math.hypot(pred_cx - lock_cx, pred_cy - lock_cy) if flow_ok else 0.0
    match_ok, match_cx, match_cy, score = template_match_locked(gray, pred_cx, pred_cy, flow_motion)
    last_match_score = score
    last_flow_ok = flow_ok

    new_cx, new_cy = lock_cx, lock_cy
    tracked_ok = False

    if flow_ok and match_ok:
        dist_fm = math.hypot(match_cx - pred_cx, match_cy - pred_cy)
        # Насколько матч ТЯНЕТ в сторону от предсказания потока.
        #
        # Поток следит за реальным движением цели и на фон не смотрит, поэтому
        # устойчивое расхождение означает, что матч зацепился за что-то другое.
        # В отличие от score, эта величина различает «держит цель» и «уверенно
        # держит не то»: сидя на фоне, матч даёт высокий score, но расходится с
        # потоком. Ни score, ни доля провалов такого показать не могут.
        _match_dbg["flow_gap"] = float(dist_fm)
        if score >= MATCH_GOOD_SCORE and dist_fm <= MAX_LOCK_STEP:
            w_m = MATCH_WEIGHT
            if MATCH_AMBIGUITY_GUARD:
                second = _match_dbg.get("second")
                if second is not None and score > 0.0:
                    # Насколько выбранный пик выигрывает у лучшего конкурента.
                    # Отрицательный запас = конкурент сильнее, матчу верить
                    # нельзя, ведём по потоку.
                    lead = (score - float(second)) / max(score, 1e-6)
                    if lead <= 0.0:
                        w_m = MATCH_WEIGHT_MIN
                    elif lead < MATCH_LEAD_FULL:
                        # Плавный переход, чтобы не дёргать вес туда-сюда на
                        # границе: на 25% запаса — полное доверие.
                        f = lead / MATCH_LEAD_FULL
                        w_m = MATCH_WEIGHT_MIN + (MATCH_WEIGHT - MATCH_WEIGHT_MIN) * f
            new_cx = (1.0 - w_m) * pred_cx + w_m * match_cx
            new_cy = (1.0 - w_m) * pred_cy + w_m * match_cy
            tracked_ok = True
        elif dist_fm <= MAX_LOCK_STEP * 0.55:
            new_cx = pred_cx
            new_cy = pred_cy
            tracked_ok = True
    elif flow_ok:
        new_cx = pred_cx
        new_cy = pred_cy
        tracked_ok = True
    elif match_ok and score >= MATCH_GOOD_SCORE:
        new_cx = match_cx
        new_cy = match_cy
        tracked_ok = True

    if tracked_ok:
        step = math.hypot(new_cx - lock_cx, new_cy - lock_cy)
        if step > MAX_LOCK_STEP:
            k = MAX_LOCK_STEP / max(step, 1e-6)
            new_cx = lock_cx + (new_cx - lock_cx) * k
            new_cy = lock_cy + (new_cy - lock_cy) * k

        lock_cx = float(clamp(new_cx, 0, LORES_W - 1))
        lock_cy = float(clamp(new_cy, 0, LORES_H - 1))
        lost_frames = 0
        auto_reacq_attempts = 0   # успешно идём — сбрасываем счётчик восстановлений

        if frame_index % FLOW_REFRESH_EVERY == 0:
            prev_pts = refresh_flow_points(gray, lock_cx, lock_cy, lock_w, lock_h)
        prev_gray = gray.copy()

        if not FREEZE_TEMPLATE and match_ok and score >= 0.60:
            cur_tmpl = build_template(gray, lock_cx, lock_cy, lock_w, lock_h)
            # Размер шаблона следует за размером коробки, поэтому при
            # изменении масштаба цели формы перестают совпадать. Раньше в этом
            # случае обновление ПРОПУСКАЛОСЬ — то есть именно на сближении,
            # когда коробка растёт, шаблон переставал обновляться и оставался
            # в старом мелком масштабе. Он покрывал всё меньшую долю цели,
            # матчер цеплялся за случайную деталь внутри объекта и уползал к
            # краю, а потом и на фон.
            #
            # Асимметрия наблюдалась именно поэтому: при УДАЛЕНИИ шаблон
            # оказывается КРУПНЕЕ цели, захватывает фон вокруг и потому
            # остаётся заякоренным — там сбоя не было.
            #
            # Теперь при смене размера шаблон пересчитывается в новый масштаб,
            # а не выбрасывается: накопленный вид цели сохраняется.
            if cur_tmpl.shape == template_gray.shape:
                template_gray = cv2.addWeighted(
                    template_gray, 1 - TEMPLATE_UPDATE_ALPHA,
                    cur_tmpl, TEMPLATE_UPDATE_ALPHA, 0)
            elif TEMPLATE_RESCALE_ON_SIZE_CHANGE and template_base is not None:
                # Размер изменился. Пересчитывать НАКОПЛЕННЫЙ шаблон нельзя:
                # каждый cv2.resize — это интерполяция, то есть размытие, и
                # оно накапливается. Размер коробки гуляет (в логе 16 -> 43 ->
                # 16 -> 40), значит пересчётов десятки, и шаблон превращался в
                # кашу — средний score упал с 0.643 до 0.498.
                #
                # Вместо этого берём ЧИСТЫЙ шаблон текущего кадра в новом
                # масштабе. Накопленный вид теряется, но это разовое событие
                # на смену масштаба, а не деградация каждые несколько кадров.
                # Прежний код в этом месте не делал НИЧЕГО, из-за чего на
                # сближении шаблон застревал в старом масштабе — здесь мы
                # по-прежнему следуем за размером, но без размытия.
                # Масштабируем ЭТАЛОН, снятый при захвате, а не текущий кадр
                # и не накопленный шаблон.
                #
                # Не текущий кадр: TEMPLATE_SCALE=2.0 значит, что шаблон
                # вчетверо больше коробки — три четверти его площади это фон.
                # Свежий вырез приносит В ШАБЛОН текущий фон, и матчер потом
                # честно находит этот фон. Так лок и уходил на похожий по
                # цвету фон (score 0.726 -> 0.561, замерено на борту).
                #
                # Не накопленный: каждый resize размывает, размытие копится,
                # 30 пересчётов съедали всю детализацию (1043 -> 4.7).
                #
                # Эталон снят на цели при захвате и не меняется, поэтому
                # масштабируется ровно один раз в любой новый размер.
                template_gray = cv2.resize(
                    template_base, (cur_tmpl.shape[1], cur_tmpl.shape[0]),
                    interpolation=cv2.INTER_LINEAR)

        # Периодическая адаптация размера коробки. Раз в SIZE_ADAPT_EVERY_FRAMES
        # при уверенном матче запрашиваем заново связную компоненту под текущим
        # центром лока и сдвигаем lock_w/lock_h в её сторону. Решает «дрейф
        # зацепом за край» при сближении — коробка растёт вместе с целью.
        # Измеряем, ПОЧЕМУ адаптация размера не срабатывает. По логам борта
        # коробка стоит на значении по умолчанию (8 px в координатах трекинга)
        # в 76%% кадров и почти не растёт, хотя объект бывает крупным. Гейта
        # два — порог score и допустимый диапазон оценки, — и без записи
        # непонятно, какой именно закрыт.
        if SIZE_ADAPT_ENABLED and frame_index % SIZE_ADAPT_EVERY_FRAMES == 0:
            # Область поиска растягиваем под ТЕКУЩИЙ размер коробки, иначе
            # крупная цель заведомо в неё не помещается и измерить её нельзя.
            est_w, est_h = estimate_size_at_position(
                gray, lock_cx, lock_cy, cur_w=max(lock_w, lock_h))
            _match_dbg["size_est"] = est_w if est_w is not None else -1.0
            if not match_ok:
                _match_dbg["size_skip"] = 1        # матча нет
            elif score < SIZE_ADAPT_MIN_SCORE:
                _match_dbg["size_skip"] = 2        # score ниже порога
            elif est_w is None:
                _match_dbg["size_skip"] = 3        # измерить не удалось
            elif not (SIZE_ADAPT_MIN_W <= est_w <= SIZE_ADAPT_MAX_W
                      and SIZE_ADAPT_MIN_W <= est_h <= SIZE_ADAPT_MAX_W):
                _match_dbg["size_skip"] = 4        # вне допустимого диапазона
            else:
                _match_dbg["size_skip"] = 0        # применена
                # Размер меняем только когда его ДЕЙСТВИТЕЛЬНО измерили.
                # Прежде при неудаче подставлялся минимум, и коробка каждые
                # 10 кадров ужималась обратно.
                lock_w = lock_w * (1.0 - SIZE_ADAPT_ALPHA) + est_w * SIZE_ADAPT_ALPHA
                lock_h = lock_h * (1.0 - SIZE_ADAPT_ALPHA) + est_h * SIZE_ADAPT_ALPHA

        box = lores_box_to_main(lock_cx, lock_cy, lock_w, lock_h)
        with state_lock:
            track_state = TRACK_STATE_TRACKED
            target_visible = True
            target_controllable = True
            target_box_main = box
            overlay_text = "TRACKED"
            overlay_color = COLOR_RED
        update_control_from_target()
    else:
        lost_frames += 1
        prev_gray = gray.copy()
        if lost_frames <= HOLD_FRAMES:
            box = lores_box_to_main(lock_cx, lock_cy, lock_w, lock_h)
            with state_lock:
                track_state = TRACK_STATE_HOLD
                target_visible = True
                target_controllable = False
                target_box_main = box
                overlay_text = "HOLD"
                overlay_color = COLOR_YELLOW
            update_control_from_target()
        elif lost_frames <= LOST_LIMIT:
            with state_lock:
                track_state = TRACK_STATE_LOST
                target_visible = False
                target_controllable = False
                target_box_main = None
                overlay_text = "LOST"
                overlay_color = COLOR_WHITE
            update_control_from_target()
        else:
            if REQUIRE_AUX_TOGGLE_AFTER_LOST:
                with state_lock:
                    track_state = TRACK_STATE_LOST
                    target_visible = False
                    target_controllable = False
                    target_box_main = None
                    overlay_text = "LOST/TOGGLE"
                    overlay_color = COLOR_WHITE
                update_control_from_target()
            else:
                reset_tracking(to_acq=True)
                update_control_from_target()


def print_debug_once_per_second():
    """Раз в DEBUG_PERIOD секунд:
       FPS, state, override, RC со стика (RPYT), наш CMD, что РЕАЛЬНО ушло в FC,
       motor outputs (если Betaflight отдаёт MSP_MOTOR).
    """
    global fps_t0, fps_frames, fps_current
    fps_frames += 1
    now = time.monotonic()
    if now - fps_t0 < DEBUG_PERIOD:
        return

    fps_current = fps_frames / max(now - fps_t0, 1e-6)
    fps_frames = 0
    fps_t0 = now

    if not DEBUG_PRINT:
        return

    with state_lock:
        ch = list(app_state.get("rc_channels", [1500] * 8))
        motors = list(app_state.get("motors", []))
        ov = override_active
        st = track_state
        r_out = int(global_roll_cmd)
        p_out = int(global_pitch_cmd)
        y_out = int(global_yaw_cmd)
        t_out = int(global_throttle_cmd)
        sent = list(app_state.get("last_sent_channels", [1500] * 8))

    c0 = int(ch[0]) if len(ch) > 0 else 1500
    c1 = int(ch[1]) if len(ch) > 1 else 1500
    c2 = int(ch[2]) if len(ch) > 2 else 1500
    c3 = int(ch[3]) if len(ch) > 3 else 1000
    s0 = int(sent[0]) if len(sent) > 0 else 1500
    s1 = int(sent[1]) if len(sent) > 1 else 1500
    s2 = int(sent[2]) if len(sent) > 2 else 1500
    s3 = int(sent[3]) if len(sent) > 3 else 1000

    mot_s = " ".join([f"M{i+1}:{int(v)}" for i, v in enumerate(motors[:4])]) if motors else "M:NA"

    print(
        f"FPS:{fps_current:5.1f} | {st:<7} | OV:{ov} | "
        f"RPYT in: R{c0:4d} P{c1:4d} Y{c2:4d} T{c3:4d} | "
        f"CMD R{r_out:4d} P{p_out:4d} Y{y_out:4d} T{t_out:4d} | "
        f"SENT AETR R{s0:4d} P{s1:4d} T{s2:4d} Y{s3:4d} | "
        f"{mot_s}",
        flush=True
    )

