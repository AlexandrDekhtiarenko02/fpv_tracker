"""Крестик — центр зоны поиска, НЕ кандидат с безусловным приоритетом
(пересмотрено после разбора оператора поверх 64949ec).

БЫЛО (до этой правки): отдельная, более мелкомасштабная проверка "есть ли
структура ПОД самим крестиком" — она срабатывала первой и решала захват
безусловно, даже не заглядывая в остальную зону. Формально это должно было
"доверять наводке пилота", но реально означало: если под самим крестиком
случайно фон, а не цель, крестик всё равно "выигрывал", хотя рядом мог
быть явно выраженный, ничем не хуже patch.

СТАЛО: крестик — ТОЛЬКО центр зоны поиска. Вершины (локальные максимумы
выраженности — разность мелкого и крупного размытия, тот же детектор, что
и раньше, НЕ переписан) ищутся по ВСЕЙ зоне одним и тем же способом, и
побеждает БЛИЖАЙШАЯ к крестику. Если она оказывается ровно под ним —
результат совпадает с прежним поведением; если рядом — берётся она, а не
пустое место под крестиком.

ПОЧЕМУ БЛИЖАЙШЕЕ, А НЕ САМОЕ ВЫРАЖЕННОЕ (не изменилось). Выраженность
отвечает на вопрос «что тут вообще есть», а не «что пилот имел в виду»:
край дороги, столб или тень почти всегда контрастнее небольшой цели, и по
яркости захват уезжал бы на них. Поэтому выраженность работает порогом
(есть кандидат или нет), а выбирает — близость к крестику.

Второе требование не менее важно: над однородной поверхностью зона обязана
МОЛЧАТЬ (вернуть None) — по новой архитектуре это теперь означает прямой
отказ acquisition (см. test_acq_ambiguity_reject.py), а не молчаливый
захват сырого крестика.
"""
import io
import math
import os
import re

import numpy as np
import cv2

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = io.open(os.path.join(_ROOT, "tracker.py"), encoding="utf-8").read()

ns = {"np": np, "cv2": cv2, "math": math}
for name in ("ACQ_SNAP_ENABLED", "ACQ_SNAP_SIGMA_MELKO", "ACQ_SNAP_SIGMA_KRUPNO",
             "ACQ_SNAP_PEAK_OKNO", "ACQ_SNAP_YADRO_LORES",
             "ACQ_SNAP_SIGMA_YADRO", "ACQ_SNAP_YADRO_MIN_OTN",
             "ACQ_SNAP_YADRO_MIN_ABS", "ACQ_SNAP_MIN_OTN", "ACQ_SNAP_MIN_ABS"):
    ns[name] = eval(re.search(r"^%s = (.+?)(?:\s+#.*)?$" % name, src, re.M).group(1))
W, H = 320, 240
ns["CENTER_X_LORES"], ns["CENTER_Y_LORES"] = W // 2, H // 2
ns["ACQ_SNAP_RADIUS_LORES"] = 30
exec(re.search(r"^def _nayti_pyatno.*?(?=\n\ndef )", src, re.S | re.M).group(0), ns)
nayti = ns["_nayti_pyatno"]

rng = np.random.default_rng(7)


def fon(shum=3.0):
    f = np.full((H, W), 120.0, np.float32)
    f += rng.normal(0, shum, f.shape)
    return np.clip(cv2.GaussianBlur(f, (0, 0), 1.0), 0, 255).astype(np.uint8)


print("=== 1. Цель РОВНО под крестиком — находится, dx=dy≈0, независимо "
      "от того, что рядом ===")
# Рядом нарочно ставим предмет ЗАМЕТНО контрастнее — в СТАРОЙ архитектуре
# это ничего не решало (крестик побеждал безусловно), в НОВОЙ тоже не
# должно решать: цель под крестиком — БЛИЖАЙШАЯ по построению (расстояние
# 0), сравнение выраженности с соседом в выборе не участвует вовсе.
for podpis, jarche in (("равный", 40), ("много ярче", 15)):
    g = fon()
    cv2.circle(g, (W // 2, H // 2), 5, 60, -1)            # под крестиком
    cv2.circle(g, (W // 2 + 20, H // 2 + 4), 7, jarche, -1)   # рядом, ярче
    p = nayti(g)
    assert p is not None, "не нашла ничего"
    x, y, margin, dx, dy = p
    sdvig = math.hypot(dx, dy)
    print("    сосед %-11s -> margin=%.2f сдвиг от крестика %.1f px"
          % (podpis, margin, sdvig))
    assert sdvig < 0.5, (
        "захват уехал на соседа (%s), сдвиг %.1f px: цель под крестиком "
        "была ближайшей по построению и обязана была победить" % (podpis, sdvig))

print("\n=== 2. Под крестиком пусто — берём ближайшее в зоне (dx/dy != 0) "
      "===")
for sdvig_celi, storona in ((22, "вправо"), (-24, "влево")):
    g = fon()
    cx, cy = W // 2 + sdvig_celi, H // 2 - 4
    cv2.circle(g, (cx, cy), 6, 35, -1)
    p = nayti(g)
    assert p is not None, "цель %s не найдена вовсе" % storona
    x, y, margin, dx, dy = p
    oshibka = math.hypot(x - cx, y - cy)
    print("    цель %s: найдено (%.0f,%.0f) dx=%.0f dy=%.0f, промах %.1f px"
          % (storona, x, y, dx, dy, oshibka))
    assert oshibka <= 6.0, "промах %.1f px" % oshibka
    assert abs(dx) > 5.0 or abs(dy) > 5.0, (
        "dx/dy почти нулевые, хотя цель стояла заметно в стороне от крестика")

print("\n=== 3. Пустой фон — зона обязана молчать (None) ===")
molchit = sum(1 for _ in range(12) if nayti(fon()) is None)
print("    промолчала в %d случаях из 12" % molchit)
assert molchit >= 11, (
    "на однородном фоне зона срабатывает (%d из 12): захват станет "
    "непредсказуемым там, где пилот целится вручную" % molchit)

print("\n=== 4. Под крестиком пусто: ближнее слабое побеждает дальнее "
      "яркое ===")
g = fon()
cv2.circle(g, (W // 2 + 12, H // 2 + 3), 5, 95, -1)     # ближе, скромнее
cv2.circle(g, (W // 2 + 26, H // 2 - 8), 7, 25, -1)     # дальше, ярче
p = nayti(g)
assert p is not None
x, y, margin, dx, dy = p
d_bl = math.hypot(x - (W // 2 + 12), y - (H // 2 + 3))
d_dl = math.hypot(x - (W // 2 + 26), y - (H // 2 - 8))
print("    выбрано (%.0f,%.0f): до ближнего %.1f px, до дальнего %.1f px"
      % (x, y, d_bl, d_dl))
assert d_bl < d_dl, (
    "выбрано дальнее яркое: значит решает выраженность, а не близость")

print("\n=== 5. Фактурный предмет: захват не улетает ДАЛЕКО, пока крестик "
      "гуляет внутри одного предмета ===")
# Здесь ломались два прежних подхода. У фактуры вершин много, и требование
# «своя вершина под крестиком» гнало захват с выбранного места на соседнюю
# вершину ТОГО ЖЕ предмета. В НОВОЙ архитектуре нет отдельного "режима
# крестика" — но "ближайшая вершина" сама по себе обязана оставаться
# близко к крестику (в пределах самого предмета), не улетать на его
# противоположный край.
def faktura(cx, cy, r, seed):
    g = fon()
    rr = np.random.default_rng(seed)
    y, x = np.mgrid[0:H, 0:W]
    vnutri = (x - cx) ** 2 + (y - cy) ** 2 <= r * r
    shum = rr.normal(0, 26, (H, W))
    shum = cv2.GaussianBlur(shum.astype(np.float32), (0, 0), 1.3)
    pole = g.astype(np.float32)
    pole[vnutri] = np.clip(70 + shum, 0, 255)[vnutri]
    return np.clip(pole, 0, 255).astype(np.uint8)


uehalo = 0
for smesh in (-8, -4, 0, 4, 8):
    # Крестик стоит В РАЗНЫХ местах одного фактурного предмета (радиус 16).
    g = faktura(W // 2 - smesh, H // 2, 16, 100 + smesh)
    p = nayti(g)
    assert p is not None, "на фактуре не нашла ничего (смещение %+d)" % smesh
    x, y, margin, dx, dy = p
    sdvig = math.hypot(dx, dy)
    if sdvig > 16.0:   # радиус самого предмета — за его пределы не должно уезжать
        uehalo += 1
        print("    смещение %+d: УЕХАЛО на (%.0f,%.0f), сдвиг %.1f px"
              % (smesh, x, y, sdvig))
    else:
        print("    смещение %+d: сдвиг от крестика %.1f px (внутри предмета)"
              % (smesh, sdvig))
assert uehalo == 0, (
    "%d из 5 точек фактурного предмета захват уехал ЗА ЕГО ПРЕДЕЛЫ: пилот "
    "выбирает часть предмета, а находится другая, далёкая его часть" % uehalo)

print("\n=== 6. margin растёт вместе с контрастом (отчёт 25.09, п.3, "
      "сохранено после пересмотра п.A: margin — не бинарный порог, а "
      "мера) ===")
# ИЗОЛИРОВАННЫЙ генератор (не общий module-level rng выше) — результат
# этой секции не должен зависеть от того, сколько случайных чисел успели
# забрать секции 1-5 ДО неё. ОДНА И ТА ЖЕ позиция (ровно под крестиком) в
# обоих случаях — сравнивается ТОЛЬКО контраст, чтобы не зависеть от
# относительной чувствительности sal к разным геометриям (расстояние,
# размер), только что найденной хрупкой при переносе прежней, уже
# убранной uzko-калибровки на новую единую sal-based margin.
_rng6 = np.random.default_rng(31337)


def _fon6():
    f = np.full((H, W), 120.0, np.float32)
    f += _rng6.normal(0, 3.0, f.shape)
    return np.clip(cv2.GaussianBlur(f, (0, 0), 1.0), 0, 255).astype(np.uint8)


g_weak = _fon6()
cv2.circle(g_weak, (W // 2, H // 2), 5, 100, -1)     # слабый контраст (120 -> 100)
p_weak = nayti(g_weak)
g_strong = _fon6()
cv2.circle(g_strong, (W // 2, H // 2), 5, 20, -1)    # сильный контраст (120 -> 20)
p_strong = nayti(g_strong)
assert p_weak is not None and p_strong is not None
assert p_strong[2] > p_weak[2], (
    "margin сильного контраста (%.2f) не больше margin слабого (%.2f) — "
    "margin обязан расти вместе с контрастом, иначе это не мера, а "
    "просто ещё один бинарный порог" % (p_strong[2], p_weak[2]))
print("    слабый контраст (120->100): margin=%.2f; сильный (120->20): "
      "margin=%.2f — margin реально масштабируется с контрастом"
      % (p_weak[2], p_strong[2]))

print("\n=== 7. Возвращаемое значение — ровно 5 элементов (x, y, margin, "
      "dx, dy), margin>=1.0 по построению (иначе не прошёл бы порог) ===")
g = fon()
cv2.circle(g, (W // 2 + 10, H // 2 - 6), 6, 40, -1)
p = nayti(g)
assert p is not None
assert len(p) == 5, "ожидали 5-tuple (x, y, margin, dx, dy), получили %r" % (p,)
x, y, margin, dx, dy = p
assert margin >= 1.0, "margin=%.3f < 1.0 — не должен был пройти порог" % margin
assert abs((x - dx) - W // 2) < 1e-3 and abs((y - dy) - H // 2) < 1e-3, (
    "dx/dy не согласованы с (x,y) и крестиком")
print("    (x=%.1f, y=%.1f, margin=%.2f, dx=%.1f, dy=%.1f) — форма и "
      "согласованность dx/dy подтверждены" % (x, y, margin, dx, dy))

print("\nOK: крестик — центр зоны поиска, побеждает ближайшая вершина "
      "независимо от того, есть ли отклик ровно под ним; margin и dx/dy "
      "дают честную диагностику выбора")
