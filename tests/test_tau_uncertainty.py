"""Время до контакта пишется с оценкой надёжности, а не голым числом.

Сверка с GPS 4 сентября 2026, одиннадцать заходов: девять дали отношение к
истине 1.0-1.6, а два — 0.12 и 0.65. Оба провала пришлись на самое медленное
сближение (истинное время 12.9 и 10.9 с). Причина понятна: tau = постоянная,
делённая на прирост рамки, и когда сближение вялое, прирост тонет в шуме.

Голое «T 6.9s» об этом не сообщает ничего. Закон наведения обязан различать
шесть секунд, известные с точностью до полусекунды, и те же шесть секунд,
которые на деле могут быть и двадцатью.
"""
import math
import os
import sys

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(_ROOT, "tools"))
import offline  # noqa: E402

t = offline.load_tracker()
cols = t._FLIGHT_LOG_COLUMNS.split(",")

print("=== 1. Колонки есть ===")
for imya in ("tau_s", "tau_sigma_s", "growth_raw", "growth_sigma",
             "gps_alt_m"):
    assert imya in cols, "нет колонки %s" % imya
    print("    %-16s позиция %d" % (imya, cols.index(imya)))

print("\n=== 2. Несглаженный прирост копится отдельно от сглаженного ===")
# Без обоих рядов нельзя проверить, отстаёт ли сглаживание — а именно оно
# первый подозреваемый в завышении времени на 25%.
assert hasattr(t, "_growth_raw"), "нет хвоста несглаженных приростов"
assert t._growth_raw.maxlen and 8 <= t._growth_raw.maxlen <= 64, (
    "хвост длиной %s: слишком короткий не даст оценить разброс, слишком "
    "длинный будет помнить давно прошедшее" % t._growth_raw.maxlen)
print("    хвост на %d кадров" % t._growth_raw.maxlen)

print("\n=== 3. Надёжность падает, когда прирост тонет в шуме ===")


def sigma(rost, shum):
    """Погрешность времени при данном приросте и разбросе прироста."""
    tau = (1.0 / rost) * t.NOMINAL_DT
    return tau, tau * (shum / rost)


shum = 0.004
prezhde = None
for rost in (0.05, 0.02, 0.01, 0.006, 0.004):
    tau, sig = sigma(rost, shum)
    otn = sig / tau * 100
    print("    прирост %.3f -> T %5.1f с, погрешность %5.1f с (%.0f%%)"
          % (rost, tau, sig, otn))
    if prezhde is not None:
        assert otn > prezhde, (
            "относительная погрешность обязана расти при вялом сближении")
    prezhde = otn

print("\n=== 4. Вялое сближение помечается как ненадёжное ===")
# Именно этот случай и провалился в полёте: отношение к истине 0.12.
tau, sig = sigma(0.004, shum)
assert sig / tau > 0.6, (
    "при приросте на уровне шума время обязано быть помечено красным, "
    "а вышло %.0f%%" % (100 * sig / tau))
tau, sig = sigma(0.05, shum)
assert sig / tau < 0.25, (
    "при бодром сближении время обязано считаться надёжным, а вышло %.0f%%"
    % (100 * sig / tau))
print("    вялое -> %.0f%%, бодрое -> %.0f%%"
      % (100 * sigma(0.004, shum)[1] / sigma(0.004, shum)[0],
         100 * sigma(0.05, shum)[1] / sigma(0.05, shum)[0]))

print("\n=== 5. Высота с GPS пишется: барометр до сих пор не сверен ===")
# Дальность стоит на угле и высоте. Угол сверен по GPS, высота — нет, хотя
# ошибка высоты входит в дальность один в один: dR/R = dH/H.
assert cols.index("gps_alt_m") > 0
print("    gps_alt_m на позиции", cols.index("gps_alt_m"))

print("\nOK: время до контакта больше не притворяется одинаково надёжным")
