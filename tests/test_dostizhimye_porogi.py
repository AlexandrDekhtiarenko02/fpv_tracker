"""Порог не может стоять выше того, что измеряемая величина способна выдать.

ЭТО ЛОВИТ НАСТОЯЩУЮ ПОЛОМКУ, А НЕ ГИПОТЕТИЧЕСКУЮ. Режим сближения имел
запасной признак: если времени до контакта нет — судить по доле кадра,
CLOSING_BOX_FRAC_THRESHOLD = 0.18. Он не срабатывал НИ РАЗУ и не мог:

    сторона рамки ограничена SIZE_ADAPT_MAX_W = 150 px (жёстко, в коде),
    кадр 640x480,
    значит доля кадра не больше 150*150/(640*480) = 0.0732,
    а порог стоял на 0.18 — в 2.5 раза выше физического предела.

Замер по 27 заходам коммита 9d4ecb6 это подтвердил: максимум доли кадра за
всё время 0.0260, а в момент, когда время до контакта проходит свои 4 с (то
есть ровно тогда, когда запасной признак и должен был бы сработать), — 0.0170.
Двадцать три процента кадров шли без времени до контакта, и все они
опрашивали ветку, которая отвечает «нет» при любых входных данных.

ПОЧЕМУ ЭТО НЕ ПОЙМАЛ СУЩЕСТВОВАВШИЙ ТЕСТ. Он был — в test_size_lock.py, и
назывался ровно «предел коробки допускает режим сближения». Он считал
LOCK_MAX_W**2 / (W * H) = 120**2 / (320 * 240) = 0.1875, сравнивал с 0.18 и
проходил с запасом в 4%. Ошибся дважды и в одну сторону: взял кадр 320x240
своей синтетической сцены вместо MAIN_W x MAIN_H = 640x480 (вчетверо по
площади) и предел замка LOCK_MAX_W вместо предела коробки SIZE_ADAPT_MAX_W.
Два промаха сложились в ложное подтверждение.

Отсюда правило этого файла: обе стороны сравнения берутся из tracker.py, из
тех самых констант, которыми пользуется сам код, и ни одна не вводится здесь
руками.

Опасность такой ошибки в том, что она невидима. Код читается как страховка,
тесты на поведение проходят (ветка ведь отрабатывает), в логах ровно ноль
срабатываний — и это выглядит как «просто не было случая».

Проверка тут арифметическая и потому надёжнее любого прогона: порог сравнивается
с пределом, который задан другими константами того же файла.
"""
import io
import os
import re

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = io.open(os.path.join(_ROOT, "tracker.py"), encoding="utf-8").read()

ns = {}
for imya in ("MAIN_W, MAIN_H", "HIRES_TRACKING", "TRACK_SCALE",
             "SIZE_ADAPT_MAX_W", "SIZE_ADAPT_MIN_W"):
    m = re.search(r"^%s = (.+?)(?:\s+#.*)?$" % re.escape(imya), src, re.M)
    assert m is not None, "не нашёл в tracker.py: %s" % imya
    exec("%s = %s" % (imya, m.group(1)), ns)

MAIN_W, MAIN_H = ns["MAIN_W"], ns["MAIN_H"]
MAX_W = ns["SIZE_ADAPT_MAX_W"]
PREDEL_BOX_FRAC = float(MAX_W * MAX_W) / float(MAIN_W * MAIN_H)


print("=== 1. Предел доли кадра ===")
if True:
    assert 0.0 < PREDEL_BOX_FRAC < 0.5, (
        "доля кадра при максимальной рамке %d px в кадре %dx%d = %.4f"
        % (MAX_W, MAIN_W, MAIN_H, PREDEL_BOX_FRAC))


print("    максимум доли кадра = %d*%d/(%d*%d) = %.4f"
      % (MAX_W, MAX_W, MAIN_W, MAIN_H, PREDEL_BOX_FRAC))

print("\n=== 2. Ни один порог по доле кадра не выше предела ===")
if True:
    plohie = []
    for m in re.finditer(r"^([A-Z][A-Z0-9_]*BOX_FRAC[A-Z0-9_]*) = "
                         r"([0-9.]+)(?:\s+#.*)?$", src, re.M):
        imya, znach = m.group(1), float(m.group(2))
        if znach > PREDEL_BOX_FRAC:
            plohie.append((imya, znach))
    assert not plohie, (
        "порог выше физически достижимой доли кадра %.4f (рамка не больше "
        "%d px в кадре %dx%d): %s. Такой порог не сработает никогда."
        % (PREDEL_BOX_FRAC, MAX_W, MAIN_W, MAIN_H,
           ", ".join("%s = %s" % p for p in plohie)))


    print("    ни одного недостижимого порога не найдено")

print("\n=== 3. Мёртвая ветка убрана из режима сближения ===")
if True:
    assert "in_closing = box_frac >=" not in src, (
        "режим сближения снова судит по доле кадра — она мешает размер цели "
        "с дальностью, и порога, верного сразу для крупной далёкой цели и "
        "мелкой близкой, не существует")
    m = re.search(r"elif _tau_now is not None:.*?\n    else:\n(.*?)\n\n",
                  src, re.S)
    assert m is not None, "не нашёл ветку выбора режима сближения"
    assert "in_closing = False" in m.group(1), (
        "без времени до контакта режим сближения должен быть выключен явно")


    print("    без времени до контакта режим сближения выключен явно")

print("\n=== 4. Предел рамки с запасом над минимальной ===")
if True:
    assert MAX_W >= 4 * ns["SIZE_ADAPT_MIN_W"], (
        "предел рамки %d px слишком близок к минимальному %d px"
        % (MAX_W, ns["SIZE_ADAPT_MIN_W"]))
    print("    предел %d px против минимума %d px" % (MAX_W, ns["SIZE_ADAPT_MIN_W"]))

print("\nOK: порогов выше физически достижимого нет")
