"""Компенсация тангажа поправляет прицел, а не подменяет наведение.

Геометрия кадра даёт 11.6 px/° (VFOV 41.4° на 480 px): именно на столько
уезжает цель при наклоне носа. Это НЕ помеха, а сигнал, ради которого контур
существует — отвечать на него и значит наводиться.

Отсюда жёсткая граница. Компенсация, равная геометрии, делает контур слепым к
собственному тангажу; компенсация БОЛЬШЕ неё разворачивает обратную связь в
положительную: нос вниз -> «ошибка» растёт -> нос ещё ниже. Это проверено
дорого: 9 сентября 2026 коэффициент подняли до 5.0 по замеру 6.67 px/°, и
следующий вылет дал переднее сальто — тангаж 82°, команда на упоре шесть
кадров подряд. Замер был верный, но мерял геометрию наведения, а не то, что
подлежит компенсации.

Компенсации принадлежит только упреждение по траектории: в пикировании вектор
скорости идёт ниже оси камеры. Это единицы пикселей на градус.

Второе условие — отсчёт от тангажа В МОМЕНТ ЗАХВАТА. От горизонта поправка
выдумывает ошибку на первом же кадре: пилот локается уже в пикировании, цель
ровно в перекрестье, а компенсация от 13.5° сразу даёт 20-67 px на пустом
месте.
"""
import os
import sys

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(_ROOT, "tools"))
import offline  # noqa: E402

t = offline.load_tracker()

print("=== 1. Коэффициент близок к замеренному ===")
k = t.PIXELS_PER_PITCH_DEG
print("    PIXELS_PER_PITCH_DEG = %.2f (геометрия кадра 11.59)" % k)
assert 0.0 <= k <= 4.0, (
    "коэффициент %.2f слишком велик. Это упреждение по траектории (единицы "
    "px/°), а не геометрия наведения (11.6 px/°). На 5.0 контур сделал "
    "переднее сальто" % k)
assert k < 11.59 / 2.0, (
    "коэффициент %.2f подошёл к половине масштаба кадра: компенсация начнёт "
    "съедать сам сигнал наведения" % k)

print("\n=== 1б. Отсчёт ведётся от тангажа при захвате ===")
import io as _io
_src = _io.open(os.path.join(_ROOT, "tracker.py"), encoding="utf-8").read()
assert "smoothed_pitch_deg - _pitch_pri_loke" in _src, (
    "компенсация снова считается от горизонта: она выдумает ошибку на первом "
    "же кадре, если лок берут в пикировании")
assert "_pitch_pri_loke = None" in _src, "отсчёт не сбрасывается между локами"
print("    отсчёт от угла при захвате — на месте")

print("\n=== 2. Компенсация больше не упирается в предел ===")
# Предел существует как страховка от абсурда, а не как рабочий режим.
# При 40° пикирования компенсация обязана оставаться внутри него.
for pitch in (10.0, 20.0, 30.0, 40.0):
    comp = pitch * k
    print("    тангаж %2.0f° -> компенсация %5.1f px (предел %.0f)"
          % (pitch, comp, t.MAX_PITCH_COMP_PX))
    assert comp < t.MAX_PITCH_COMP_PX, (
        "на %.0f° компенсация %.0f px упирается в предел %.0f — она перестаёт "
        "следить за наклоном и прицел встаёт колом"
        % (pitch, comp, t.MAX_PITCH_COMP_PX))

print("\n=== 3. Компенсация не должна перебивать саму ошибку ===")
# Замерено: типичная ошибка прицела ДО компенсации около 11 px, 90-й
# процентиль 70. Компенсация того же порядка — это поправка. Вшестеро
# больше — это уже не поправка, а помеха.
tipichnaya_oshibka = 70.0     # 90-й процентиль по 46 заходам
comp_20 = 20.0 * k
print("    ошибка прицела (90%%): %.0f px, компенсация на 20°: %.0f px"
      % (tipichnaya_oshibka, comp_20))
assert comp_20 < 3.0 * tipichnaya_oshibka, (
    "компенсация %.0f px против типичной ошибки %.0f px: поправка не может "
    "быть втрое больше того, что поправляет" % (comp_20, tipichnaya_oshibka))

print("\nOK: компенсация поправляет прицел, а не подменяет его")
