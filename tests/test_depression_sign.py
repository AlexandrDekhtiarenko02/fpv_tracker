"""Знак угла снижения: нос вниз обязан давать ПОЛОЖИТЕЛЬНЫЙ угол.

Знак здесь установлен по замеру, а не по соглашению из документации:

  1. Картинка, которую получает трекер, НЕ перевёрнута — небо сверху
     (подтверждено оператором). Значит низ кадра это низ мира.
  2. Замерено по заходу 141912: цель в кадре смещается на -12.2 px на
     каждый +1° тангажа от FC, связь -0.92 на 207 кадрах.

При неперевёрнутой картинке цель уезжает ВВЕРХ, когда нос идёт ВНИЗ.
Значит рост тангажа от FC = нос вниз. Дальность считается до точки на
ЗЕМЛЕ, поэтому нос вниз обязан давать положительный угол снижения; при
обратном знаке дальность получалась бы до точки ПОЗАДИ аппарата.
"""
import io, os, re

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = io.open(os.path.join(_ROOT, "tracker.py"), encoding="utf-8").read()

m = re.search(r"^\s*depression = (.+)$", src, re.M)
assert m, "не нашёл вычисление угла снижения"
expr = m.group(1)
print("в коде:  depression =", expr)

MAIN_H = eval(re.search(r"^MAIN_W, MAIN_H = (.+?)(?:\s+#.*)?$", src, re.M).group(1))[1]
CAMERA_VFOV_DEG = eval(re.search(r"^CAMERA_VFOV_DEG = (.+?)(?:\s+#.*)?$", src, re.M).group(1))
CAMERA_TILT_DEG = eval(re.search(r"^CAMERA_TILT_DEG = (.+?)(?:\s+#.*)?$", src, re.M).group(1))
deg_per_px = CAMERA_VFOV_DEG / float(MAIN_H)

def depression(fc_pitch, off_deg):
    return eval(expr, {"float": float, "fc_pitch": fc_pitch, "off_deg": off_deg,
                       "CAMERA_TILT_DEG": CAMERA_TILT_DEG})

print("\n=== 1. Нос вниз -> угол снижения положительный ===")
d = depression(20.0, 0.0)
print("    тангаж +20° (нос вниз), цель по центру -> угол %+.1f°" % d)
assert d > 0, "нос вниз даёт %.1f°: дальность считалась бы назад" % d

print("\n=== 2. Нос вверх -> угол отрицательный, дальности нет ===")
d = depression(-20.0, 0.0)
print("    тангаж -20° (нос вверх) -> угол %+.1f°" % d)
assert d < 0

print("\n=== 3. Цель НИЖЕ в кадре -> угол больше ===")
low = depression(10.0, +5.0)
high = depression(10.0, -5.0)
print("    цель ниже центра: %+.1f°, выше центра: %+.1f°" % (low, high))
assert low > high, "цель ниже в кадре обязана давать больший угол снижения"

print("\n=== 4. Тот самый заход: несли, наклонив к цели ===")
# Замерено: средний тангаж +14°, цель около центра. Прежний код объявлял это
# взглядом на 14° ВЫШЕ горизонта, что и объясняло 'дальность не считалась'.
d = depression(14.0, 0.0)
print("    тангаж +14° -> угол %+.1f° (прежний код давал %+.1f°)" % (d, -14.0))
assert d > 0

print("\n=== 5. Дальность выходит осмысленной ===")
import math
for alt_m, dep in ((30.0, 20.0), (30.0, 45.0), (50.0, 10.0)):
    r = alt_m / math.tan(math.radians(dep))
    print("    высота %.0f м, угол %.0f° -> дальность %.0f м" % (alt_m, dep, r))
    assert 0 < r < 1000

print("\nOK: нос вниз даёт положительный угол, дальность считается вперёд")
