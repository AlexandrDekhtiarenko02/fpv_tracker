"""Занижение тангажа в полёте — отдельная величина, а не часть наклона камеры.

Замерено 4 сентября 2026 по сверке с GPS, 27 заходов. В полёте цель стоит
ровно в центре кадра, значит ось камеры смотрит точно на неё, и её угол ниже
горизонта равен истинному. Полётник при этом даёт тангаж на десять градусов
меньше, чем требует геометрия, и занижение растёт со скоростью: +4.6° на 5
м/с, +17.4° на 17. На земле, где аппарат неподвижен, занижения нет.

Раньше обе величины пряталсь в одной константе 0.5°, и потому она была верна
в воздухе и ломала замеры на земле: на десяти метрах прибор показывал семь.

Проверено на отложенной половине заходов:
    наклон 10, без поправки       132.2% ошибки дальности
    наклон 0.5 (прежняя заплатка)  20.6%
    наклон 10 + эта поправка       13.5%
"""
import io
import os
import re
import sys

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(_ROOT, "tools"))
import offline  # noqa: E402

t = offline.load_tracker()

print("=== 1. Наклон камеры физический ===")
print("    CAMERA_TILT_DEG = %.1f (на борту камера стоит под 10°)"
      % t.CAMERA_TILT_DEG)
assert 8.0 <= t.CAMERA_TILT_DEG <= 12.0, (
    "наклон %.1f разошёлся с физическим 10° — если это новая калибровка, "
    "обнови и обоснование" % t.CAMERA_TILT_DEG)

print("\n=== 2. Поправка растёт со скоростью и сходится с замером ===")
zamer = ((2.5, 4.6), (7.5, 9.5), (12.5, 11.5), (17.5, 17.4))
for v, bylo in zamer:
    p = min(t.PITCH_BIAS_MAX,
            max(0.0, t.PITCH_BIAS_PER_MS * v + t.PITCH_BIAS_BASE))
    print("    %5.1f м/с: модель %+5.1f°, замерено %+5.1f°" % (v, p, bylo))
    assert abs(p - bylo) < 5.0, (
        "на %.1f м/с модель даёт %+.1f°, а замерено %+.1f° — расхождение "
        "больше пяти градусов делает поправку вреднее её отсутствия"
        % (v, p, bylo))

print("\n=== 3. На неподвижном аппарате поправки почти нет ===")
# Иначе сломаются наземные замеры, ради которых всё и разводилось.
p0 = max(0.0, t.PITCH_BIAS_PER_MS * 0.0 + t.PITCH_BIAS_BASE)
print("    на нуле скорости: %+.1f°" % p0)
assert p0 < 4.0, (
    "на неподвижном аппарате поправка %+.1f° — наземные замеры снова поедут"
    % p0)

print("\n=== 4. Без скорости не поправляем вовсе ===")
# Ни GPS, ни бега земли — значит и разгона нет, о котором речь.
src = io.open(os.path.join(_ROOT, "tracker.py"), encoding="utf-8").read()
i = src.index("out[\"pitch_bias_deg\"] = popravka")
kusok = src[i - 900:i]
assert "if skorost is None" in kusok and "popravka = 0.0" in kusok, (
    "при неизвестной скорости поправка обязана быть нулевой, иначе она "
    "поедет туда, где её измерить было нечем")
print("    да, при неизвестной скорости поправка нулевая")

print("\n=== 5. Поправка ограничена сверху ===")
p = min(t.PITCH_BIAS_MAX,
        max(0.0, t.PITCH_BIAS_PER_MS * 100.0 + t.PITCH_BIAS_BASE))
print("    при нелепых 100 м/с: %+.1f° (предел %.1f)" % (p, t.PITCH_BIAS_MAX))
assert p <= t.PITCH_BIAS_MAX, "предел не работает"
assert t.PITCH_BIAS_MAX <= 30.0, (
    "предел %.0f° слишком велик: замеры кончаются на 20 м/с, дальше это "
    "уже не поправка, а выдумка" % t.PITCH_BIAS_MAX)

print("\n=== 6. Величина пишется в лог ===")
cols = t._FLIGHT_LOG_COLUMNS.split(",")
assert "pitch_bias_deg" in cols, (
    "без этой колонки на разборе не отличить угол, который померили, от "
    "угла, который поправили")
print("    pitch_bias_deg на позиции", cols.index("pitch_bias_deg"))

print("\nOK: наклон камеры означает наклон камеры, а не сумму двух ошибок")
