"""Тангаж доводится до текущего кадра по гироскопу.

ЗАМЕРЕНО НА 5070 КАДРАХ коммита 9d4ecb6: возраст угла из MSP_ATTITUDE
медианно 76 мс, в 10% кадров больше 228, максимум 439. При вращении 42 °/с
(90-й процентиль) это ошибка в 9.7 градуса, в клевке при 90 °/с — все 18.

Ломалось от этого всё, что складывает угол полётника с положением цели в
кадре: угол визирования, компенсация тангажа, дальность. Величины относятся к
РАЗНЫМ моментам, и разность копит ложную скорость — из-за неё поправка прицела
вставала в упор, и аппарат клевал носом.
"""
import os
import sys

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(_ROOT, "tools"))
import offline  # noqa: E402

t = offline.load_tracker()


# ВРЕМЯ БЕРЁТСЯ С ЗАПАСОМ ОТ НУЛЯ, и это не придирка.
#
# На macOS time.monotonic() считает от старта ПРОЦЕССА и в начале теста равен
# долям секунды. Отняв от него возраст в 228 мс, получаем отрицательную метку
# — а ноль и меньше в коде означает «время не задано», и функция честно
# отказывается работать. На малине Linux считает от загрузки, значения
# большие, и в полёте этого не бывает.
#
# На этой ловушке в проекте уже теряли время однажды. Поэтому берём заведомо
# большую базу, а не системные часы.
BAZA = 10000.0


def podat(ugol, vozrast_s, gyro_units, gyro_vozrast_s=0.0):
    tek = BAZA
    with t.state_lock:
        t.app_state["fc_pitch_deg"] = ugol
        t.app_state["fc_pitch_ts"] = tek - vozrast_s
        t.app_state["gyro"] = (0, gyro_units, 0)
        t.app_state["imu_ts"] = tek - gyro_vozrast_s
    return t.svezhiy_tangazh(tek)


print("=== 1. Свежий угол не трогаем ===")
u, v = podat(20.0, 0.0, 0)
print("    возраст 0, вращения нет -> %.2f°" % u)
assert abs(u - 20.0) < 0.01, "свежий угол изменён"

print("\n=== 2. Устаревший угол доводится ===")
# Замеренные случаи: медиана и 90-й процентиль.
for vozr, vrash_dps, podpis in ((0.076, 11.4, "медиана"), (0.228, 42.6, "90%")):
    units = vrash_dps / t.GYRO_UNIT_DPS
    u, v = podat(20.0, vozr, units)
    dolzhno = 20.0 + vrash_dps * vozr
    print("    %-8s возраст %3.0f мс, вращение %4.1f °/с -> %.2f° (ожидалось %.2f)"
          % (podpis, vozr * 1000, vrash_dps, u, dolzhno))
    assert abs(u - dolzhno) < 0.3, (
        "поправка не та: %.2f вместо %.2f" % (u, dolzhno))

print("\n=== 3. Поправка ограничена ===")
# При 90 °/с и 200 мс истинная ошибка 18°, но такой экстраполяции верить уже
# нельзя — лучше вернуть меньше, чем выдумать больше.
u, v = podat(20.0, 0.20, 90.0 / t.GYRO_UNIT_DPS)
print("    вращение 90 °/с, возраст 200 мс -> %.1f° (предел поправки %.0f°)"
      % (u, t.EXTRAP_MAX_DEG))
assert u <= 20.0 + t.EXTRAP_MAX_DEG + 0.01, "поправка вышла за предел"
assert t.EXTRAP_MAX_DEG <= 20.0, "предел %.0f° — это уже выдумка" % t.EXTRAP_MAX_DEG

print("\n=== 3б. Порог годности покрывает замеренные возрасты ===")
# Замерено: возраст 90-го процентиля 228 мс. Прежний порог 200 мс отсекал их,
# и компенсация в этих кадрах молча падала в ноль — ступенька на ровном месте.
ZAMER_90 = 0.228
print("    порог %.0f мс, замеренный 90%%-й возраст %.0f мс"
      % (t.FC_PITCH_TIMEOUT * 1000, ZAMER_90 * 1000))
assert t.FC_PITCH_TIMEOUT > ZAMER_90, (
    "порог %.0f мс ниже замеренного 90-го процентиля (%.0f) — в каждом "
    "десятом кадре компенсация будет проваливаться в ноль"
    % (t.FC_PITCH_TIMEOUT * 1000, ZAMER_90 * 1000))
assert t.FC_PITCH_TIMEOUT <= 0.5, (
    "порог %.0f мс слишком велик: экстраполяция на такой срок — выдумка"
    % (t.FC_PITCH_TIMEOUT * 1000))

print("\n=== 4. Слишком старый угол не используется вовсе ===")
u, v = podat(20.0, t.FC_PITCH_TIMEOUT + 0.1, 0)
print("    возраст %.0f мс -> %s" % ((t.FC_PITCH_TIMEOUT + 0.1) * 1000, u))
assert u is None, "угол старше порога всё ещё возвращается"

print("\n=== 5. Несвежий гироскоп не экстраполирует ===")
u, v = podat(20.0, 0.15, 40.0 / t.GYRO_UNIT_DPS,
             gyro_vozrast_s=t.GYRO_FRESH_S + 0.05)
print("    гироскоп устарел -> %.2f° (без поправки)" % u)
assert abs(u - 20.0) < 0.01, (
    "экстраполируем по несвежему гироскопу: поправка будет выдумкой")

print("\n=== 6. Потребители берут доведённый угол ===")
import io
src = io.open(os.path.join(_ROOT, "tracker.py"), encoding="utf-8").read()
for mesto in ("fc_pitch, _vozrast = svezhiy_tangazh(now_mono)",
              "fc_pitch, _ = svezhiy_tangazh(now_mono)"):
    assert mesto in src, "потребитель не переведён на доведённый угол: %s" % mesto
print("    компенсация тангажа и угол визирования — оба")

print("\nOK: угол доводится до кадра, и разные моменты больше не смешиваются")
