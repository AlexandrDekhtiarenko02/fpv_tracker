"""Экспозицию нельзя замораживать раньше, чем автоматика сойдётся.

Оператор: «картинка вся пересвеченная и яркая». В журнале борта видно, что
именно замораживалось:

    выдержка 32939 мкс, усиление 4.00   <- ПОТОЛОК выдержки
    выдержка 32939 мкс, усиление 4.00
    выдержка 23128 мкс, усиление 2.00   <- этот успел сойтись дальше

Камера стартует с максимальной выдержки и опускается постепенно. Прежних
фиксированных 0.5 с не хватало, и в светлой комнате замораживалась экспозиция
для ТЁМНОЙ сцены.

Здесь проверяется сама логика ожидания на модели сходящейся камеры.
"""
import io, os, re

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = io.open(os.path.join(_ROOT, "tracker.py"), encoding="utf-8").read()


def const(name):
    return eval(re.search(r"^%s = (.+?)(?:\s+#.*)?$" % name, src, re.M).group(1))


MAX_S = const("CAM_SETTLE_MAX_S")
STEP = const("CAM_SETTLE_STEP_S")
NEED = const("CAM_SETTLE_STABLE")


def settle(sequence):
    """Та же логика, что в tracker.py, но на заданной последовательности."""
    prev = None
    stable = 0
    t = 0.0
    i = 0
    while t < MAX_S:
        t += STEP
        cur = sequence[min(i, len(sequence) - 1)]
        i += 1
        if prev is not None and abs(cur[0] - prev[0]) <= max(50, prev[0] * 0.02) \
                and abs(cur[1] - prev[1]) <= 0.05:
            stable += 1
            if stable >= NEED:
                return cur, t
        else:
            stable = 0
        prev = cur
    return sequence[min(i - 1, len(sequence) - 1)], t


print("=== 1. Камера сходится не сразу — дожидаемся ===")
# Так и ведёт себя настоящая: стартует с потолка и опускается.
seq = [(32939, 4.0), (32939, 4.0), (28000, 3.0), (23128, 2.0),
       (14000, 1.5), (9000, 1.0), (8600, 1.0), (8580, 1.0), (8575, 1.0)]
val, t = settle(seq)
print("    остановились на выдержке %d мкс, усилении %.1f, спустя %.1f с"
      % (val[0], val[1], t))
assert val[0] < 12000, (
    "заморозили %d мкс — это ещё не сошедшаяся автоматика" % val[0])
assert t <= MAX_S, "ждали дольше предела"

print("\n=== 2. Прежние полсекунды заморозили бы ПОТОЛОК ===")
old = seq[int(0.5 / STEP)] if int(0.5 / STEP) < len(seq) else seq[-1]
print("    через 0.5 с было бы: выдержка %d мкс, усиление %.1f" % old)
assert old[0] > 20000, "модель не воспроизводит наблюдавшуюся картину"

print("\n=== 3. Если камера не сходится вовсе — не ждём вечно ===")
import itertools
noisy = [(30000 + (i * 977) % 3000, 4.0) for i in range(200)]
val, t = settle(noisy)
print("    прекратили ожидание через %.1f с (предел %.1f)" % (t, MAX_S))
assert t <= MAX_S + STEP, "ожидание не ограничено"

print("\n=== 4. Уже сошедшаяся камера не задерживает запуск ===")
val, t = settle([(8500, 1.0)] * 20)
print("    сошлась сразу, ожидание %.1f с" % t)
assert t <= STEP * (NEED + 1) + 1e-6, "лишняя задержка на исправной камере"

print("\nOK: ждём схождения, но не дольше предела")
