"""Компенсация тангажа масштабирована по ЗАМЕРУ, а не по геометрии кадра.

Геометрия кадра даёт 11.6 px/° (VFOV 41.4° на 480 px), но компенсации нужен
не масштаб кадра: аппарат, наклоняясь, одновременно движется к цели, и увод
выходит меньше геометрического.

Замерялось дважды, и второй замер отменил первый. Первый (2.02 px/°) снят
целиком в режиме наблюдения — там рулил пилот и компенсировал наклон руками.
Второй, по полётам с включённым управлением 9 сентября 2026: на плавных
участках (>=10 кадров, <=2.5°/кадр) медиана 6.67 px/°, половины выборки 5.20
и 8.58. Участки рывков дают 1.71 и в расчёт не идут — на них трекер теряет
цель, рамка замирает, и меряется срыв слежения, а не геометрия.

Точное число этими данными не определяется (половины расходятся на 51%), зато
надёжно, что оно выше 2.0 в 2.6-4.3 раза. Стоит 5.0 — ниже обеих половин:
недобор безопаснее перебора, потому что выше 11.6 обратная связь становится
положительной.
"""
import os
import sys

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(_ROOT, "tools"))
import offline  # noqa: E402

t = offline.load_tracker()

print("=== 1. Коэффициент близок к замеренному ===")
k = t.PIXELS_PER_PITCH_DEG
print("    PIXELS_PER_PITCH_DEG = %.2f (замерено 6.67, половины 5.20 и 8.58)" % k)
assert 3.0 <= k <= 9.0, (
    "коэффициент %.2f вне замеренного диапазона 5.20..8.58. Ниже — контур "
    "принимает собственный наклон за движение цели и бьёт в упор; выше 11.6 "
    "(масштаб кадра) обратная связь становится положительной" % k)
assert k < 11.59, (
    "коэффициент %.2f не ниже геометрического масштаба кадра: прицел будет "
    "уезжать дальше цели, и нос повалится всё круче" % k)

print("\n=== 2. Компенсация больше не упирается в предел ===")
# Предел существует как страховка от абсурда, а не как рабочий режим.
# При 40° пикирования компенсация обязана оставаться внутри него.
for pitch in (10.0, 20.0, 30.0, 40.0):
    comp = pitch * k
    print("    тангаж %2.0f° -> компенсация %5.1f px (предел %.0f)"
          % (pitch, comp, t.MAX_PITCH_COMP_PX))
    assert comp < t.MAX_PITCH_COMP_PX, (
        "на %.0f° компенсация %.0f px упирается в предел %.0f — она перестаёт "
        "следить за наклоном и прицел встаёт колом"
        % (pitch, comp, t.MAX_PITCH_COMP_PX))

print("\n=== 3. Компенсация не должна перебивать саму ошибку ===")
# Замерено: типичная ошибка прицела ДО компенсации около 11 px, 90-й
# процентиль 70. Компенсация того же порядка — это поправка. Вшестеро
# больше — это уже не поправка, а помеха.
tipichnaya_oshibka = 70.0     # 90-й процентиль по 46 заходам
comp_20 = 20.0 * k
print("    ошибка прицела (90%%): %.0f px, компенсация на 20°: %.0f px"
      % (tipichnaya_oshibka, comp_20))
assert comp_20 < 3.0 * tipichnaya_oshibka, (
    "компенсация %.0f px против типичной ошибки %.0f px: поправка не может "
    "быть втрое больше того, что поправляет" % (comp_20, tipichnaya_oshibka))

print("\nOK: компенсация поправляет прицел, а не подменяет его")
