"""Газ добавляется когда заход БУКСУЕТ, а не когда цель просто далеко.

Замерено на заходах 9d4ecb6 (5070 кадров): поправка газа стояла на упоре
+120 в 13.7% кадров и НИ РАЗУ не уходила в минус.

    время до контакта  4-7 с  -> поправка    0
    время до контакта 14-15 с -> поправка  +71
    время до контакта 18-19 с -> поправка +115

Закон добавлял газ при времени больше 9 с. А при захвате издалека оно велико
ПО СУЩЕСТВУ ДЕЛА — 90-й процентиль 19.3 с. В начале каждого пологого захода
газ получал почти полный упор, и аппарат лез вверх. Пилот видел это как
«швыряет вверх на пологом заходе».

Та же ошибка, что была с наклоном: большая величина принята за беду, хотя это
просто расстояние. Отличает одно от другого УБЫВАНИЕ: на нормальном сближении
время убывает секунда в секунду, каким бы большим оно ни было.
"""
import ast
import io
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = io.open(os.path.join(ROOT, "tracker.py"), encoding="utf-8").read()
tree = ast.parse(src)
zn = {}
for node in tree.body:
    if isinstance(node, ast.Assign) and len(node.targets) == 1:
        imya = getattr(node.targets[0], "id", None)
        if imya:
            try:
                zn[imya] = ast.literal_eval(node.value)
            except Exception:
                pass


def dolya(ubyv):
    """Доля поправки газа при таком ходе времени."""
    if ubyv <= zn["TAU_UBYV_PLOHO"]:
        return 0.0
    return max(0.0, min(1.0, (ubyv - zn["TAU_UBYV_PLOHO"])
                        / (-zn["TAU_UBYV_PLOHO"])))


print("=== 1. Здоровое сближение газ не трогает ===")
print("  %-10s %s" % ("убывание", "доля поправки"))
for u in (-1.2, -1.0, -0.6, -0.4, -0.2, 0.0, 0.5):
    print("  %+-10.1f %.0f%%" % (u, 100 * dolya(u)))
assert dolya(-1.0) == 0.0, (
    "при нормальном убывании (-1 с/с) газ всё ещё добавляется — значит "
    "«далеко» по-прежнему путается с «буксуем»")
assert dolya(-0.6) == 0.0, "лёгкое отставание от нормы не повод жать газ"

print("\n=== 2. Остановка сближения газ включает ===")
assert dolya(0.0) >= 0.9, (
    "время не убывает вовсе, а газ почти не добавляется — закон перестал "
    "работать там, ради чего написан")
assert dolya(0.5) == 1.0, "время РАСТЁТ, а поправка не полная"

print("\n=== 3. Знак не переворачивается ===")
# Первая версия формулы делила на отрицательное число, и при нулевом
# убывании множитель уходил в минус, переворачивая поправку.
for u in (-1.5, -0.4, 0.0, 2.0):
    assert 0.0 <= dolya(u) <= 1.0, (
        "доля %.2f при убывании %+.1f вне [0,1] — поправка перевернётся"
        % (dolya(u), u))

print("\n=== 4. Далёкая цель со здоровым сближением ===")
# Тот самый случай из логов: время 19 с, но убывает как положено.
ZAMER_TAU, ZAMER_POPRAVKA = 19.0, 115.0
bylo = (ZAMER_TAU - zn["TAU_THROTTLE_HI_S"]) * zn["TAU_THROTTLE_GAIN"]
bylo = min(bylo, zn["TAU_THROTTLE_MAX"])
stalo = bylo * dolya(-1.0)
print("    время %.0f с, убывает -1.0 с/с: было %+.0f PWM, стало %+.0f"
      % (ZAMER_TAU, bylo, stalo))
assert abs(bylo - ZAMER_POPRAVKA) < 20, (
    "расчёт не сходится с замером (%.0f против %.0f) — значит воспроизводим "
    "не ту беду" % (bylo, ZAMER_POPRAVKA))
assert stalo == 0.0, "далёкая цель со здоровым сближением всё ещё жмёт газ"

print("\n=== 5. Ход времени меряется наклоном по окну ===")
assert "_tau_hist.append((now_mono, float(_tau_now)))" in src, (
    "ход времени считается не по окну: на разностях он будет шумом")
assert zn["TAU_UBYV_OKNO_S"] > zn["TAU_FIT_WINDOW_S"], (
    "окно хода (%.1f с) не длиннее окна самой оценки (%.1f) — мерить ход по "
    "тому же окну значит мерить его же шум"
    % (zn["TAU_UBYV_OKNO_S"], zn["TAU_FIT_WINDOW_S"]))
assert src.count("_tau_ubyvanie = 0.0") >= 2, (
    "ход не сбрасывается между заходами")
print("    окно %.1f с, не менее %d точек" % (zn["TAU_UBYV_OKNO_S"],
                                              zn["TAU_UBYV_MIN_TOCHEK"]))

print("\n=== 6. По умолчанию считаем, что НЕ закрываемся ===")
# Пока ход не измерен, газ добавлять не за что — но и запрещать нельзя:
# начальное значение 0 означает «не убывает», то есть поправка разрешена.
# Важно, что это осознанный выбор, а не случайность.
assert "_tau_ubyvanie = 0.0" in src
print("    начальное значение 0.0 — до первого замера ход неизвестен")

print("\nOK: газ жмёт буксующий заход, а не далёкую цель")
