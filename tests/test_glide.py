"""Разгон включается по состоянию захода, а не по секундомеру.

Прежний разгон заводился таймером на каждом переходе в controllable и держал
наклон 3.5 секунды независимо ни от чего. По реальным логам он срабатывал
тогда, когда нужный наклон уже был набран (медиана тангажа в те кадры
+20.3°), и его угловой контур стоял в насыщении в 93% кадров, ни разу не
объявив угол достигнутым за 4678 кадров — из-за перепутанного знака.
Проверяется, что обе беды не вернулись.
"""
import ast
import io
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = io.open(os.path.join(ROOT, "tracker.py"), encoding="utf-8").read()
tree = ast.parse(src)

zn = {}
for node in tree.body:
    if isinstance(node, ast.Assign) and len(node.targets) == 1:
        imya = getattr(node.targets[0], "id", None)
        if imya:
            try:
                zn[imya] = ast.literal_eval(node.value)
            except Exception:
                pass

# 1. Знак углового контура согласован с прицельным. Обе константы описывают
#    один физический факт: чтобы опустить нос, PWM надо уменьшить.
assert zn["PITCH_SIGN"] == -1, "PITCH_SIGN изменён — сверь с ним и разгон"
assert zn["PITCH_PWM_TO_FC_ANGLE_SIGN"] == zn["PITCH_SIGN"], (
    "знаки прицеливания и разгона разошлись: угловой контур снова будет "
    "гнуть нос не туда либо стоять в насыщении")

# 2. Цель угла берётся ПОЛОЖИТЕЛЬНОЙ: нос вниз = положительный fc_pitch,
#    проверено по 12.9 тыс. кадров тремя независимыми признаками.
assert "(-abs(target_deg)) - cur" not in src, (
    "цель угла снова отрицательная: ошибка не обнулится никогда, контур "
    "встанет в насыщение и разгон опять станет разомкнутым")
assert "(+abs(target_deg)) - cur" in src, "не нашёл вычисление ошибки угла"

# 3. Таймерный разгон выключен, и его состояние больше не заводится
#    переходом в controllable.
assert zn["LAUNCH_ENABLED"] is False, (
    "таймерный разгон снова включён: он держит наклон 3.5 с независимо от "
    "того, нужен он или нет")
assert "trigger_launch" not in src, "триггер по переходу в controllable вернулся"

# 4. Наклон регулируется временем до контакта, и границы согласованы с
#    остальным контуром: ниже порога сближения тангаж принадлежит прицелу,
#    выше верхней границы газа обе оси считают заход затянутым одинаково.
assert zn["GLIDE_ENABLED"] is True
assert zn["GLIDE_TAU_OFF_S"] == zn["CLOSING_TAU_S"], (
    "нижняя граница наклона разошлась с порогом режима сближения: в финале "
    "к прицельному тангажу будет добавляться посторонний наклон")
assert zn["GLIDE_TAU_FULL_S"] == zn["TAU_THROTTLE_HI_S"], (
    "наклон и газ считают заход затянутым по разным порогам — потянут в "
    "разные стороны")
assert zn["GLIDE_TAU_OFF_S"] < zn["GLIDE_TAU_FULL_S"], "границы перевёрнуты"
assert 5.0 <= zn["GLIDE_MIN_PITCH_DEG"] <= 25.0, (
    "наклон вне разумного: по данным 15° это около 10 м/с, 30° уже 16 м/с")
assert zn["GLIDE_MAX_PWM"] <= zn["LAUNCH_MAX_PWM"], (
    "фоновый наклон не должен быть резче короткого манёвра")

# 5. В режиме наблюдения наклон не считается: там трекер вообще не рулит.
assert "GLIDE_ENABLED and not OBSERVE_ONLY" in src, (
    "наклон считается и в режиме наблюдения")

print("разгон: знак согласован, таймер убран, границы сшиты с газом и "
      "режимом сближения")
print("  наклон %g° при времени до контакта >= %g с, снят при <= %g с, "
      "потолок %g PWM"
      % (zn["GLIDE_MIN_PITCH_DEG"], zn["GLIDE_TAU_FULL_S"],
         zn["GLIDE_TAU_OFF_S"], zn["GLIDE_MAX_PWM"]))
